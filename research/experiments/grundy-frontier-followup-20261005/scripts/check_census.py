#!/usr/bin/env python3
"""Independent direct-safe-family audit of a bounded clutter census.

All nonempty downward families on <=5 named points are generated by deciding
safe subsets in ascending order, without enumerating forbidden antichains.
Every saved witness, including six-point links, is checked directly.
"""
from collections import Counter
from pathlib import Path
import argparse
import json
if not __debug__:
    raise SystemExit('Assertions are required.')

def families(n):
    N=1<<n
    def visit(s,safe):
        if s==N:
            yield safe
            return
        yield from visit(s+1,safe)
        if all((safe>>(s^(1<<p)))&1 for p in range(n) if s>>p&1):
            yield from visit(s+1,safe|(1<<s))
    yield from visit(1,1)

def values(n,safe):
    N=1<<n;g=[0]*N;h=[0]*N
    for s in range(N-1,-1,-1):
        if not (safe>>s)&1:
            continue
        children=[s|(1<<p) for p in range(n) if not s>>p&1 and (safe>>(s|(1<<p)))&1]
        seen={g[c] for c in children}
        while g[s] in seen:
            g[s]+=1
        h[s]=max((h[c]+1 for c in children),default=0)
    return g[0],h[0]

def transformed(n,safe):
    return ((1<<(1<<n))-1) | (safe<<(1<<n))

def full_vertices(n,safe):
    return all(safe>>(1<<p)&1 for p in range(n))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--census',type=Path,default=Path(__file__).resolve().parents[1]/'output/census.json')
    ap.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'output/independent-audit.json');args=ap.parse_args()
    rows=json.loads(args.census.read_text())['rows'];audits=[];witnesses=0
    for n in range(1,6):
        hist=[Counter(),Counter()];counts=[0,0]
        for safe in families(n):
            if full_vertices(n,safe):
                hist[0][values(n,safe)]+=1;counts[0]+=1
            hist[1][values(n+1,transformed(n,safe))]+=1;counts[1]+=1
        for mode in (0,1):
            original=next(r for r in rows if r['n']==n and r['mode']==mode)
            expected=Counter({(r['grundy'],r['height']):r['count'] for r in original['grundy_height_histogram']})
            assert expected==hist[mode] and original['families']==counts[mode]
            audits.append({'n':n,'mode':mode,'all_families':counts[mode],'status':'VERIFIED'})
    for row in rows:
        for entry in row['grundy_height_histogram']:
            safe=int(entry['link_safe_mask']);n=row['n']
            if row['mode']==1:
                safe=transformed(n,safe);n+=1
            else:
                assert full_vertices(n,safe)
            assert values(n,safe)==(entry['grundy'],entry['height'])
            witnesses+=1
    # A near-simplex does not have a general SG <=2*deficit+1 bound.
    link=26810491531689983
    assert values(7,transformed(6,link))==(4,6)
    facets=[s for s in range(64) if link>>s&1 and all(not(link>>(s|(1<<p))&1) for p in range(6) if not s>>p&1)]
    out={'all_histograms_through_five_named_points':audits,'all_saved_witnesses':witnesses,
         'six_point_counts_not_independently_reenumerated':True,
         'failed_sg_deficit_bound':{'vertices':7,'height':6,'grundy':4,'link_facets':facets,
             'claim':'g<=2*(vertices-height)+1','status':'COUNTEREXAMPLE','ceiling_question_settled':False}}
    args.output.write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
if __name__=='__main__':main()
