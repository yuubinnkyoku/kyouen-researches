"""Probe equality witnesses A(p)=h+2 for primes beyond the verified range.

Reduction (K0334 / frontier-geometry proof section 5): a safe set of size h+2
is exactly {0, d, p-d} plus one element of each other pair {i, p-i}; safety
reduces to signed NAE3/4 + origin clauses. A model of clauses_for_pair(p,edges,d)
therefore yields an equality witness. Edges are generated by forbidden_edges.cpp.
SAT calls run under WSL cadical via DIMACS (no pysat dependency).
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "research/experiments/structural-lemmas-2026-10-02/checks"))
from parabola_half_bound import clauses_for_pair  # noqa: E402
from quadratic_modular_barrier import prime  # noqa: E402

TMP = Path(tempfile.gettempdir()) / "opencode"
TMP.mkdir(parents=True, exist_ok=True)


def to_wsl(path: Path) -> str:
    p = path.resolve()
    rest = str(p)[len(p.drive):].replace("\\", "/")
    return f"/mnt/{p.drive.rstrip(':').lower()}{rest}"


def cadical(cnf_text: str):
    path = TMP / f"_probe_{os.getpid()}.cnf"
    path.write_text(cnf_text, encoding="ascii")
    win = to_wsl(path)
    r = subprocess.run(
        ["wsl", "-d", "Ubuntu", "-u", "root", "--", "bash", "-c",
         f"cadical --quiet {win}"],
        capture_output=True, text=True)
    sat = "s SATISFIABLE" in r.stdout
    model = None
    if sat:
        lits = []
        for line in r.stdout.splitlines():
            if line.startswith("v "):
                lits += [int(x) for x in line[2:].split() if x != "0"]
        model = {l for l in lits if l > 0}
    return sat, model


def probe(p, gen, max_doubles=None, gen_cache=None):
    edges = [tuple(map(int, line.split())) for line in
             subprocess.check_output([gen, str(p)], text=True).splitlines()]
    h = (p - 1) // 2
    doubles = list(range(h, 0, -1))
    if max_doubles:
        doubles = doubles[:max_doubles]
    for d in doubles:
        clauses = clauses_for_pair(p, edges, d)
        body = "".join(" ".join(map(str, c)) + " 0\n" for c in clauses)
        cnf = f"p cnf {h} {len(clauses)}\n" + body
        sat, upper = cadical(cnf)
        if sat:
            params = sorted([0, d, p - d] + [p - i if i in upper else i
                                             for i in range(1, h + 1) if i != d])
            selected = set(params)
            safe = (len(params) == h + 2 and len(set(params)) == h + 2
                    and not any(set(e) <= selected for e in edges))
            return {"p": p, "attained": True, "double_pair": d,
                    "parameters": params, "size": len(params), "want": h + 2,
                    "safe_by_edges": safe, "forbidden_edges": len(edges),
                    "clauses": len(clauses)}
    return {"p": p, "attained": False, "forbidden_edges": len(edges),
            "want": h + 2, "doubles_tried": len(doubles)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--generator", required=True)
    ap.add_argument("--start", type=int, required=True)
    ap.add_argument("--end", type=int, required=True)
    ap.add_argument("--max-doubles", type=int, default=1)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    records = []
    for p in range(args.start | 1, args.end + 1, 2):
        if not prime(p):
            continue
        t0 = time.time()
        rec = probe(p, args.generator, args.max_doubles)
        rec["seconds"] = round(time.time() - t0, 2)
        records.append(rec)
        print(f"p={p} attained={rec['attained']} "
              f"d={rec.get('double_pair')} sec={rec['seconds']}", flush=True)
        Path(args.out).write_text(json.dumps(records, indent=2) + "\n",
                                  encoding="utf-8")


if __name__ == "__main__":
    main()
