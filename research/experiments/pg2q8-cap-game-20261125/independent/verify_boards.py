def parse_board(path):
    with open(path, "r", encoding="utf-8") as f:
        raw = [ln.split() for ln in f if ln.strip()]
    n, b = int(raw[0][0]), int(raw[0][1])
    lines = []
    for row in raw[1:]:
        vals = [int(t) for t in row]
        k = vals[0]
        pts = vals[1:]
        assert len(pts) == k, (k, len(pts))
        lines.append(pts)
    assert len(lines) == b, (len(lines), b)
    return n, lines


def design_checks(n, lines, expected_k, label):
    """Common 'linear space' checks: line sizes, distinct lines, point range,
    every point pair on exactly one line, point degrees."""
    out = []
    out.append((f"{label}: #lines = {len(lines)}", len(lines)))
    sizes = sorted({len(L) for L in lines})
    out.append((f"{label}: line sizes", sizes))
    out.append((f"{label}: lines distinct", len({tuple(sorted(L)) for L in lines}) == len(lines)))
    flat = [p for L in lines for p in L]
    out.append((f"{label}: all points in 0..{n-1}", min(flat) >= 0 and max(flat) < n))
    out.append((f"{label}: all points used", len({p for p in flat}) == n))
    out.append((f"{label}: point degree (should all equal {expected_k[0] if expected_k else '?'})",
                sorted({sum(1 for L in lines if p in L) for p in range(n)})))
    # pairs on exactly one line
    pair_count = [[0] * n for _ in range(n)]
    for L in lines:
        for a in range(len(L)):
            for b in range(a + 1, len(L)):
                pair_count[L[a]][L[b]] += 1
                pair_count[L[b]][L[a]] += 1
    bad = [(a, b) for a in range(n) for b in range(a + 1, n) if pair_count[a][b] != 1]
    out.append((f"{label}: every point pair on exactly one line", len(bad) == 0,
                bad[:5]))
    return out


def pg_checks(n, lines):
    out = design_checks(n, lines, (9,), "PG")
    # line pairs meet in exactly one point
    sets = [set(L) for L in lines]
    bad = []
    for i in range(len(lines)):
        for j in range(i + 1, len(lines)):
            if len(sets[i] & sets[j]) != 1:
                bad.append((i, j, len(sets[i] & sets[j])))
    out.append(("PG: every line pair meets in exactly 1 point", len(bad) == 0, bad[:5]))
    # count incidences / degree check explicitly
    deg = [0] * n
    for L in lines:
        for p in L:
            deg[p] += 1
    out.append(("PG: every point on exactly 9 lines", set(deg) == {9}, sorted(set(deg))))
    return out


def ag_checks(n, lines):
    out = design_checks(n, lines, (9,), "AG")
    sets = [set(L) for L in lines]
    m = len(lines)
    # parallel classes: lines are parallel iff disjoint.  Build connected components
    # of the disjointness graph (in an affine plane these are the parallel classes).
    parent = list(range(m))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb

    for i in range(m):
        for j in range(i + 1, m):
            if not (sets[i] & sets[j]):
                union(i, j)
    classes = {}
    for i in range(m):
        classes.setdefault(find(i), []).append(i)
    out.append(("AG: number of parallel classes", len(classes)))
    out.append(("AG: class sizes", sorted(len(v) for v in classes.values())))
    ok_classes = True
    detail = []
    for root, members in classes.items():
        u = set()
        pairwise_disjoint = True
        for i in members:
            if u & sets[i]:
                pairwise_disjoint = False
            u |= sets[i]
        if not pairwise_disjoint or len(u) != n:
            ok_classes = False
            detail.append((len(members), len(u), pairwise_disjoint))
    out.append(("AG: each class = 8 pairwise disjoint lines covering all points",
                ok_classes, detail))
    # every point on exactly one line of each class
    ok_part = True
    for root, members in classes.items():
        cnt = [0] * n
        for i in members:
            for p in sets[i]:
                cnt[p] += 1
        if set(cnt) != {1}:
            ok_part = False
    out.append(("AG: each parallel class partitions the point set", ok_part))
    deg = [0] * n
    for L in lines:
        for p in L:
            deg[p] += 1
    out.append(("AG: every point on exactly 9 lines", set(deg) == {9}, sorted(set(deg))))
    return out


# ----------------------------------------------------------------------------
# isomorphism search (point bijection taking lines to lines)
# ----------------------------------------------------------------------------

def find_isomorphism(n, lines_b, lines_m, fixed_pairs, verbose=False):
    """Search for a bijection phi: board points -> model points with
    phi(line) a model line for every board line.  fixed_pairs are forced.

    Propagation: whenever two points of a board line are mapped, the image line
    is forced and every other point of that board line is restricted to it.
    Branching on the unassigned point with the smallest domain (MRV).

    Completeness note: for a projective/affine plane the automorphism group of
    the model is transitive on ordered frames, so if an isomorphism exists one
    exists with the chosen frame mapped to the standard frame.  Hence fixing a
    frame loses nothing.
    """
    lpt_b = [[] for _ in range(n)]
    for li, L in enumerate(lines_b):
        for p in L:
            lpt_b[p].append(li)
    mask_m = []
    for L in lines_m:
        mm = 0
        for p in L:
            mm |= 1 << p
        mask_m.append(mm)
    pair2line = {}
    for li, L in enumerate(lines_m):
        for a in range(len(L)):
            for b in range(a + 1, len(L)):
                pair2line[(L[a], L[b])] = li
    full = (1 << n) - 1
    nodes = [0]

    def assign(phi, psi, dom, p, m):
        if phi[p] != -1:
            return phi[p] == m
        if psi[m] != -1:
            return False
        phi[p] = m
        psi[m] = p
        dom[p] = 1 << m
        bit = 1 << m
        for q in range(n):
            if phi[q] == -1:
                nd = dom[q] & ~bit
                if nd == 0:
                    return False
                dom[q] = nd
        return True

    def propagate(phi, psi, dom):
        changed = True
        while changed:
            changed = False
            for L in lines_b:
                assigned = [q for q in L if phi[q] != -1]
                if len(assigned) < 2:
                    continue
                a, b = assigned[0], assigned[1]
                key = (phi[a], phi[b]) if phi[a] < phi[b] else (phi[b], phi[a])
                mm = mask_m[pair2line[key]]
                for q in L:
                    if phi[q] == -1:
                        nd = dom[q] & mm
                        if nd == 0:
                            return False
                        if nd & (nd - 1) == 0:
                            mv = nd.bit_length() - 1
                            if not assign(phi, psi, dom, q, mv):
                                return False
                            changed = True
                        elif nd != dom[q]:
                            dom[q] = nd
                            changed = True
        return True

    def rec(phi, psi, dom):
        nodes[0] += 1
        if not propagate(phi, psi, dom):
            return None
        best = -1
        best_c = n + 1
        for p in range(n):
            if phi[p] == -1:
                c = bin(dom[p]).count("1")
                if c < best_c:
                    best_c = c
                    best = p
                    if c == 1:
                        break
        if best == -1:
            return phi[:]
        p = best
        cands = [m for m in range(n) if (dom[p] >> m) & 1]
        for m in cands:
            nphi, npsi, ndom = phi[:], psi[:], dom[:]
            if not assign(nphi, npsi, ndom, p, m):
                continue
            r = rec(nphi, npsi, ndom)
            if r is not None:
                return r
        return None

    phi = [-1] * n
    psi = [-1] * n
    dom = [full] * n
    for p, m in fixed_pairs:
        if not assign(phi, psi, dom, p, m):
            if verbose:
                print("  frame assignment failed")
            return None, nodes[0]
    res = rec(phi, psi, dom)
    return res, nodes[0]


def verify_permutation(n, lines_b, lines_m, phi):
    """phi maps board point -> model point.  Check it is a bijection and that
    the image of every board line is a model line, and conversely."""
    if len(set(phi)) != n:
        return False, "not a bijection"
    mset = {frozenset(L) for L in lines_m}
    images = []
    for L in lines_b:
        img = frozenset(phi[p] for p in L)
        if img not in mset:
            return False, f"line image not a model line: {sorted(L)}"
        images.append(img)
    if len(set(images)) != len(lines_b):
        return False, "line images not distinct"
    # converse: every model line is hit (follows from counts, check anyway)
    if set(images) != mset:
        return False, "not all model lines hit"
    return True, "ok"


def choose_pg_frame(n, lines):
    """4 points, no three collinear."""
    line_of = {}
    for li, L in enumerate(lines):
        for p in L:
            line_of[p] = li
    for a in range(n):
        for b in range(a + 1, n):
            l_ab = line_of_for_pair(lines, a, b)
            for c in range(b + 1, n):
                if c in lines[l_ab]:
                    continue
                l_ac = line_of_for_pair(lines, a, c)
                l_bc = line_of_for_pair(lines, b, c)
                for d in range(c + 1, n):
                    if d in lines[l_ab] or d in lines[l_ac] or d in lines[l_bc]:
                        continue
                    return (a, b, c, d)
    raise RuntimeError("no quadrangle found")


_PAIR_CACHE = {}


def line_of_for_pair(lines, a, b):
    key = (a, b) if a < b else (b, a)
    if key in _PAIR_CACHE:
        return _PAIR_CACHE[key]
    for li, L in enumerate(lines):
        if a in L and b in L:
            _PAIR_CACHE[key] = li
            return li
    raise KeyError((a, b))


def choose_ag_frame(n, lines):
    """Return (O, X, Y, I) with X,Y on distinct lines through O and I the fourth
    vertex of the parallelogram, i.e. I = X + Y in GF(8)^2 coordinates."""
    sets = [set(L) for L in lines]
    parallel = {}
    for i in range(len(lines)):
        for j in range(len(lines)):
            if i != j and not (sets[i] & sets[j]):
                parallel.setdefault(i, set()).add(j)
    O = 0
    X = 1
    lox = line_of_for_pair(lines, O, X)
    # Y not on line OX
    Y = None
    for y in range(n):
        if y not in sets[lox]:
            Y = y
            break
    assert Y is not None
    loy = line_of_for_pair(lines, O, Y)
    # line through X parallel to OY
    pline = None
    for cand in parallel[loy]:
        if X in sets[cand]:
            pline = cand
    assert pline is not None
    # line through Y parallel to OX
    qline = None
    for cand in parallel[lox]:
        if Y in sets[cand]:
            qline = cand
    assert qline is not None
    inter = sets[pline] & sets[qline]
    assert len(inter) == 1
    I = inter.pop()
    return O, X, Y, I


