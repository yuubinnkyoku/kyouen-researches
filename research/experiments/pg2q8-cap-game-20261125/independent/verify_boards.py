#!/usr/bin/env python3
"""
Independent verification of the PG(2,8)/AG(2,8) board files.

  * parse the two board files
  * verify the projective-plane / affine-plane axioms
  * rebuild PG(2,8) from GF(8) = GF(2)[x]/(x^3+x+1) (my own construction)
  * rebuild AG(2,8) = GF(8)^2 from the same field
  * find an explicit relabelling (point bijection) making the board's line set
    equal the constructed line set, and check it exhaustively.

Only the Python standard library is used.
"""

import itertools
import sys

BOARD_PG = "../output/board_pg2q8.txt"
BOARD_AG = "../output/board_ag2q8.txt"

# ----------------------------------------------------------------------------
# GF(8) = GF(2)[alpha]/(alpha^3 + alpha + 1), elements 0..7 = bits (a0,a1,a2)
#   element value  a0 + a1*alpha + a2*alpha^2
#   alpha^3 = alpha + 1
# ----------------------------------------------------------------------------

def gf_add(a, b):
    return a ^ b


def gf_mul(a, b):
    """schoolbook multiply then reduce with alpha^3 = alpha+1."""
    r = 0
    for i in range(3):
        if (b >> i) & 1:
            r ^= a << i
    # x^5 = x^2+x+1, x^4 = x^2+x, x^3 = x+1
    if r & 0b100000:
        r ^= 0b100111          # 32 + 7
    if r & 0b010000:
        r ^= 0b010110          # 16 + 6
    if r & 0b001000:
        r ^= 0b001011          # 8 + 3
    return r & 7


GF_MUL = [[gf_mul(a, b) for b in range(8)] for a in range(8)]
GF_INV = [None] * 8
for _a in range(1, 8):
    for _b in range(1, 8):
        if gf_mul(_a, _b) == 1:
            GF_INV[_a] = _b
assert all(GF_INV[a] is not None for a in range(1, 8))
assert len({gf_mul(a, b) for a in range(1, 8) for b in range(1, 8)}) == 7


def field_selftest():
    checks = []
    # associativity / distributivity / commutativity / identity
    ok_assoc = all(gf_mul(gf_mul(a, b), c) == gf_mul(a, gf_mul(b, c))
                   for a in range(8) for b in range(8) for c in range(8))
    checks.append(("mul associative", ok_assoc))
    ok_dist = all(gf_mul(a, gf_add(b, c)) == gf_add(gf_mul(a, b), gf_mul(a, c))
                  for a in range(8) for b in range(8) for c in range(8))
    checks.append(("mul distributes over xor-add", ok_dist))
    checks.append(("mul commutative",
                   all(gf_mul(a, b) == gf_mul(b, a) for a in range(8) for b in range(8))))
    checks.append(("one is identity", all(gf_mul(1, a) == a for a in range(8))))
    # x^3 = x+1 must hold
    x = 2
    checks.append(("alpha^3 = alpha+1", gf_mul(gf_mul(x, x), x) == gf_add(x, 1)))
    # multiplicative group cyclic of order 7 generated by alpha
    p = 1
    powers = []
    for _ in range(7):
        p = gf_mul(p, x)
        powers.append(p)
    checks.append(("alpha has order 7", powers == [2, 4, 3, 6, 7, 5, 1]))
    # every element has an inverse
    checks.append(("all nonzero invertible", all(gf_mul(a, GF_INV[a]) == 1 for a in range(1, 8))))
    # irreducible: no root of x^3+x+1 in GF(2) (already implied by field axioms)
    return checks


def gf_dot(u, v):
    s = 0
    for a, b in zip(u, v):
        s ^= gf_mul(a, b)
    return s


def normalize_vec(v):
    for c in v:
        if c != 0:
            inv = GF_INV[c]
            return tuple(gf_mul(x, inv) for x in v)
    return None


# ----------------------------------------------------------------------------
# model constructions
# ----------------------------------------------------------------------------

def build_pg_model():
    """PG(2,8): 73 points = 1-dim subspaces of GF(8)^3, 73 lines = 2-dim subspaces
    (= kernels of non-zero linear functionals).  Returns (points, lines)."""
    raw_pts = [normalize_vec(v) for v in itertools.product(range(8), repeat=3)
               if v != (0, 0, 0)]
    pts = sorted(set(raw_pts))
    assert len(pts) == 73, len(pts)
    pindex = {p: i for i, p in enumerate(pts)}
    funcs = set()
    for f in itertools.product(range(8), repeat=3):
        if f == (0, 0, 0):
            continue
        funcs.add(normalize_vec(f))
    assert len(funcs) == 73, len(funcs)
    lines = []
    for f in sorted(funcs):
        L = [pindex[p] for p in pts if gf_dot(f, p) == 0]
        assert len(L) == 9, (f, len(L))
        lines.append(sorted(L))
    return pts, lines


def build_ag_model():
    """AG(2,8) = GF(8)^2: 64 points, 72 lines in 9 parallel classes of 8."""
    pts = [(x, y) for x in range(8) for y in range(8)]
    pindex = {p: i for i, p in enumerate(pts)}
    lines = []
    for m in range(8):
        for c in range(8):
            lines.append(sorted(pindex[(x, gf_add(gf_mul(m, x), c))] for x in range(8)))
    for c in range(8):
        lines.append(sorted(pindex[(c, y)] for y in range(8)))
    return pts, lines


