"""Sanity tests for the exact permutation-group order routine in pg2q8.py.

Compares group_order() against brute-force BFS enumeration of the generated
group for small random permutation groups (n = 4, 5, 6) and for a few known
groups.  Run:  python test_group_order.py
"""

import itertools
import math
import random
import sys

import pg2q8 as G

def brute_force_order(gens):
    n = len(gens[0]) if gens else 1
    ident = tuple(range(n))
    gens = [g for g in gens if g != ident]
    if not gens:
        return 1
    seen = {ident}
    stack = [ident]
    while stack:
        x = stack.pop()
        for g in gens:
            y = G.perm_mul(x, g)
            if y not in seen:
                seen.add(y)
                stack.append(y)
    return len(seen)

def random_perm(n, rng):
    p = list(range(n))
    rng.shuffle(p)
    return tuple(p)

def main():
    rng = random.Random(20261126)
    failures = 0
    tests = 0

    # random groups, n = 4, 5, 6
    for n, trials in ((4, 40), (5, 40), (6, 25)):
        for _ in range(trials):
            k = rng.randint(1, 3)
            gens = [random_perm(n, rng) for _ in range(k)]
            bf = brute_force_order(gens)
            got = G.group_order(gens)
            tests += 1
            if bf != got:
                failures += 1
                print(f"FAIL n={n} gens={gens} brute={bf} got={got}")

    # known groups on n points
    # S_n generated by an n-cycle and a transposition
    for n in range(3, 8):
        cyc = tuple(list(range(1, n)) + [0])
        trans = tuple([1, 0] + list(range(2, n)))
        bf = brute_force_order([cyc, trans])
        got = G.group_order([cyc, trans])
        tests += 1
        if bf != got or got != math.factorial(n):
            failures += 1
            print(f"FAIL S_{n}: brute={bf} got={got}")
    # cyclic C_m and dihedral D_m acting on m points (m >= 3)
    for m in range(3, 9):
        c = tuple(list(range(1, m)) + [0])
        r = tuple([0] + list(range(m - 1, 0, -1)))   # reflection
        bf = brute_force_order([c, r])
        got = G.group_order([c, r])
        tests += 1
        if bf != got or got != 2 * m:
            failures += 1
            print(f"FAIL D_{m}: brute={bf} got={got}")

    print(f"{tests} group-order tests, {failures} failures")
    return 0 if failures == 0 else 1

if __name__ == "__main__":
    sys.exit(main())
