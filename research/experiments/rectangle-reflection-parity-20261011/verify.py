#!/usr/bin/env python3
"""Independent integer geometry and D2-orbit parity checks for q-point Kyouen rectangles."""
from collections import defaultdict
from itertools import combinations
from math import comb, gcd
import json


def canonical(nums):
    g=0
    for x in nums:
        g=gcd(g,abs(x))
    if g==0:
        raise ValueError('zero key')
    a=tuple(x//g for x in nums)
    if next(x for x in a if x)!=abs(next(x for x in a if x)):
        a=tuple(-x for x in a)
    return a


def circle_key(p,q,r):
    x,y=p; u,v=q; s,t=r
    a1=(u-x); b1=(v-y); c1=x*x+y*y-u*u-v*v
    a2=(s-x); b2=(t-y); c2=x*x+y*y-s*s-t*t
    d=a1*b2-a2*b1
    if d==0:
        return None
    an=c1*b2-c2*b1
    bn=a1*c2-a2*c1
    cn=-(d*(x*x+y*y)+an*x+bn*y)
    return canonical((d,an,bn,cn))


def line_key(p,q):
    x,y=p; u,v=q
    return canonical((v-y,x-u,(y-v)*x+(u-x)*y))


def exact_counts(w,h,qmax=8):
    pts=[(x,y) for y in range(h) for x in range(w)]
    circles=defaultdict(set)
    lines=defaultdict(set)
    for i,j in combinations(range(len(pts)),2):
        lines[line_key(pts[i],pts[j])].update((i,j))
    for i,j,k in combinations(range(len(pts)),3):
        key=circle_key(pts[i],pts[j],pts[k])
        if key is not None:
            circles[key].update((i,j,k))
    cc={q:sum(comb(len(s),q) for s in circles.values() if len(s)>=q) for q in range(4,qmax+1)}
    hh={q:sum(comb(len(s),q) for s in lines.values() if len(s)>=q) for q in range(4,qmax+1)}
    return cc,hh


def predicted(w,h,q):
    # Orbits of the Klein four-group generated by vertical/horizontal reflections.
    # Coordinate system is doubled to handle even dimensions exactly.
    radial=defaultdict(lambda: [0,0])
    seen=set()
    for y in range(h):
        for x in range(w):
            X=abs(2*x-(w-1)); Y=abs(2*y-(h-1))
            if (X,Y) in seen or X==Y==0:
                continue
            seen.add((X,Y))
            radial[X*X+Y*Y][0 if X*Y else 1]+=1
    c=0
    for u,v in radial.values():
        c+=sum(comb(u,i)*comb(v,j) for i in range(u+1) for j in range(v+1) if 4*i+2*j==q)
    if q%2==0:
        k=q//2
        line=(int(h%2==1)*comb(w//2,k) if w//2>=k else 0)
        line+=(int(w%2==1)*comb(h//2,k) if h//2>=k else 0)
    else:
        k=(q-1)//2
        line=int(w%2==1 and h%2==1)*(
            (comb(w//2,k) if w//2>=k else 0)+
            (comb(h//2,k) if h//2>=k else 0))
    return c%2,line%2


def det4(a):
    # Exact integer permutation determinant; independent of circle-key construction.
    from itertools import permutations
    s=0
    for perm in permutations(range(4)):
        inv=sum(perm[i]>perm[j] for i in range(4) for j in range(i+1,4))
        prod=1
        for i,j in enumerate(perm):
            prod*=a[i][j]
        s+=(-1 if inv%2 else 1)*prod
    return s


def brute_q4(w,h):
    pts=[(x,y) for y in range(h) for x in range(w)]
    c=l=0
    for ix in combinations(range(len(pts)),4):
        s=[pts[i] for i in ix]
        x0,y0=s[0];x1,y1=s[1]
        if all((x1-x0)*(y-y0)==(y1-y0)*(x-x0) for x,y in s[2:]):
            l+=1
        elif det4([[x,y,x*x+y*y,1] for x,y in s])==0:
            c+=1
    return c,l


def run():
    cases=0; by_size=[]
    for w in range(1,8):
        for h in range(1,8):
            cc,hh=exact_counts(w,h)
            for q in range(4,9):
                p=predicted(w,h,q)
                got=(cc[q]%2,hh[q]%2)
                assert p==got,(w,h,q,p,got)
                cases+=1
            if w<=5 and h<=5:
                assert brute_q4(w,h)==(cc[4],hh[4]),(w,h)
            assert cc[4]%2==((w//2)*(h//2)+(min(w//2,h//2) if w%2 and h%2 else 0))%2
            if (w,h) in [(4,5),(4,6),(5,5),(5,6),(6,6),(7,7)]:
                by_size.append({'width':w,'height':h,'circle4':cc[4],'line4':hh[4],
                                'circle4_parity':cc[4]%2,'line4_parity':hh[4]%2,
                                'circle8':cc[8]})
    result={'orbit_parity_cases':cases,'independent_bruteforce_q4_boards':25,
            'circle_key_count_boards':49,'examples':by_size,'status':'all passed'}
    print(json.dumps(result,indent=2,ensure_ascii=False))

if __name__=='__main__':run()
