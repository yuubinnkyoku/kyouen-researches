#!/usr/bin/env python3
"""Independent machine verification of the published rank-32 cost-16
structural preread (published 2026-11-18, commit 490a3e44bc; preread JSON
git blob 6d49ab5bea27c967e15b482b33e376510c62b857, generated by the
Python exact-int preread script cost16_survival_k32_preread_20261118.py).

Second independent derivation lane, no preread-script imports: every
structural field is re-derived machine-side from the pinned phase-B
aggregate (git blob 31bdefdb2e2cc90b706cbb8090e98eb5eece4d87) with a
freshly written row-multiplicity classifier, and the three layers of the
preread are all covered:

  1. rank32 layer: root hex/rows, exact-integer membership and A/B
     split (identity + aggregate agreement), prior hit counts/indices
     (rows 15 and 23), the four new-layer censuses over partners
     0..30 (pair 31, triple 465, quad 4,495, quint 31,465) with their
     double-row histograms and b_only four-subset drop-one profiles,
     the 158 new disjoint quads (union size exactly 8 rows each) and
     the cumulative disjoint-quad count 820 re-counted globally over
     C(32,4) (and 662 over C(31,4) for the era continuation), the full
     triple census C(32,3)=4,960 and full quint census C(32,5)=201,376
     with the era continuation against the published k=31 result JSON
     (8,797 - 2,010 = 6,787 b_only; 192,579 - 29,455 = 163,124 zero),
     the all-zero sextet census C(32,6)=906,192, and the raw-JSON
     exact-integer serialization (int fields, not doubles);
  2. rank31_regression layer: root/membership/prior hits and all four
     new-layer censuses re-derived over partners 0..29, the new quint
     double-row histogram, the full triple/quint/sextet censuses
     C(31,3)/C(31,5)/C(31,6), cross-checked against the published
     k=31 result JSON structure fields, plus the declared
     classifier_comparisons count formula;
  3. rank30_regression layer: same coverage re-derived over partners
     0..28 with C(30,3)/C(30,5)/C(30,6) full censuses;
  4. meta layer: the preread's self-declared check_count=31 /
     all_pass=true, the declared input pins, and the unknown_status
     disclaimer (11x11 empty board etc. remain UNKNOWN, no verdict).

Fetches the pinned inputs at their git blob sha1s (jsdelivr mirror with
a raw.githubusercontent.com fallback; a mirror serving stale-but-wrong
bytes fails the sha1 check and the next mirror is tried).

Usage: python3 verify_cost16_k32_preread_independent_20261118.py [--local DIR]
"""
import argparse
import hashlib
import itertools
import json
import math
import sys
import urllib.request

REPO = "yuubinnkyoku/kyouen-researches"
PATH = "research/experiments/n11-head1410-partial-parent-nonsterile-children-20261118/output"
PINS = {
    "agg": ("cost16-b-phase-groups-20261118.json", "31bdefdb2e2cc90b706cbb8090e98eb5eece4d87"),
    "k31": ("cost16-survival-k31-20261118.json", "0d9f67ee69ad4fb8aa37904ddbf6666745786807"),
    "k32pre": ("cost16-survival-k32-preread-20261118.json",
               "6d49ab5bea27c967e15b482b33e376510c62b857"),
}
# input pins the preread itself declares (checked as metadata, no fetch)
EXPECTED_INPUT_PINS = {
    "aggregate": "31bdefdb2e2cc90b706cbb8090e98eb5eece4d87",
    "k30_result": "9c24e7a30ad213d3b7675e620ec606b00f73a330",
    "k31_result": "0d9f67ee69ad4fb8aa37904ddbf6666745786807",
}


def git_blob_sha1(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\x00" % len(data) + data).hexdigest()


def fetch_bytes(name: str, want_sha: str, local_dir: str | None) -> bytes:
    if local_dir:
        data = open(f"{local_dir}/{name}", "rb").read()
    else:
        urls = [
            f"https://cdn.jsdelivr.net/gh/{REPO}@main/{PATH}/{name}",
            f"https://raw.githubusercontent.com/{REPO}/main/{PATH}/{name}",
        ]
        data = None
        shas = []
        for u in urls:
            try:
                data = urllib.request.urlopen(u, timeout=60).read()
            except Exception:
                continue
            got = git_blob_sha1(data)
            if got == want_sha:
                break
            shas.append((u.split("/")[2], got))
            data = None
        if data is None:
            raise RuntimeError(f"could not fetch {name} at pinned sha "
                               f"{want_sha} (mirror results: {shas})")
        return data
    got = git_blob_sha1(data)
    if got != want_sha:
        raise RuntimeError(f"{name}: blob sha1 {got} != pinned {want_sha}")
    return data


def fetch(name: str, want_sha: str, local_dir: str | None) -> dict:
    return json.loads(fetch_bytes(name, want_sha, local_dir))


def classify(rows, combo):
    """Row-multiplicity classifier, written independently for this
    verification (same definition as the k14 publication): 'zero' for a
    3x row or two 2x rows, 'b_only' for exactly one 2x row, 'disjoint'
    otherwise."""
    c = {}
    for i in combo:
        for r in rows[i]:
            c[r] = c.get(r, 0) + 1
    if max(c.values()) >= 3:
        return "zero"
    twos = [r for r, v in c.items() if v == 2]
    if len(twos) >= 2:
        return "zero"
    if len(twos) == 1:
        return "b_only"
    return "disjoint"


def classify2(rows, combo):
    """classify plus provenance: returns (class, doubled_row_or_None)."""
    c = {}
    for i in combo:
        for r in rows[i]:
            c[r] = c.get(r, 0) + 1
    if max(c.values()) >= 3:
        return "zero", None
    twos = [r for r, v in c.items() if v == 2]
    if len(twos) >= 2:
        return "zero", None
    if len(twos) == 1:
        return "b_only", twos[0]
    return "disjoint", None


def census(rows, combos):
    """census + b_only double-row histogram over an iterable of combos."""
    out = {"b_only": 0, "zero": 0, "disjoint": 0}
    hist = {}
    for combo in combos:
        cl, two = classify2(rows, combo)
        out[cl] += 1
        if cl == "b_only":
            hist[two] = hist.get(two, 0) + 1
    return out, hist


def ok_int_histogram(d) -> dict:
    return {int(k): v for k, v in d.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--local", default=None, help="directory with the pinned input JSONs (offline mode; sha1 still checked)")
    args = ap.parse_args()

    agg = fetch(*PINS["agg"], args.local)
    k31 = fetch(*PINS["k31"], args.local)
    p = fetch(*PINS["k32pre"], args.local)

    top = agg["derived"]["top50_by_membership"]
    memA = agg["derived"]["membership_A_part_pair_roots"]
    memB = agg["derived"]["membership_B_part_pair_roots"]
    rows = {i: tuple(e["rows_covered"]) for i, e in enumerate(top)}

    checks = []

    def ck(name, cond, extra=None):
        good = bool(cond)
        checks.append((name, good))
        print(("PASS " if good else "FAIL ") + name + (f"  {extra}" if extra is not None else ""))

    # ---- meta layer -------------------------------------------------
    ck("meta_check_count_31_all_pass_true",
       p["check_count"] == 31 and p["all_pass"] is True
       and p["schema"] == "n11-cost16-k32-preread-20261118-v1")
    ck("meta_declared_input_pins",
       all(str(p["inputs"][k]["git_blob_sha1"]) == v for k, v in EXPECTED_INPUT_PINS.items()))
    ck("meta_unknown_status_disclaimer",
       "UNKNOWN" in p["unknown_status"] and "no verdict" in p["unknown_status"])

    # ---- rank-32 layer ----------------------------------------------
    rk = p["rank32"]
    idx = 31
    ck("k32_root_rows_membership_exact",
       rk["root"] == top[idx]["root"] and sorted(rk["rows"]) == sorted(rows[idx])
       and int(rk["membership"]) == int(top[idx]["membership"]),
       (rk["root"], sorted(rk["rows"])))
    M, A, B = (int(rk["membership"]), int(rk["a_part"]), int(rk["b_part"]))
    ck("k32_membership_ab_split_identity_and_aggregate",
       A + B == M and A == int(memA[rk["root"]]) and B == int(memB[rk["root"]]),
       (str(M), str(A), str(B)))
    hits = {r: sorted(i for i in range(idx) if r in rows[i]) for r in rows[idx]}
    ck("k32_prior_hits_rows_15_23",
       ok_int_histogram(rk["prior_hits"]) == {r: len(v) for r, v in hits.items()}
       and {k: sorted(v) for k, v in rk["prior_hit_indices"].items()} == {str(r): v for r, v in hits.items()},
       {r: len(v) for r, v in hits.items()})

    nc = rk["new_census"]
    pairs = [(idx, i) for i in range(idx)]
    pc, _ = census(rows, pairs)
    ck("k32_new_pair_census",
       nc["pair"]["shared"] == pc["b_only"] and nc["pair"]["disjoint"] == pc["disjoint"]
       and pc["zero"] == 0 and nc["pair"]["total"] == 31, pc)
    tc, th = census(rows, ((idx,) + c for c in itertools.combinations(range(idx), 2)))
    ck("k32_new_triple_census_and_double_rows",
       nc["triple"]["b_only"] == tc["b_only"] and nc["triple"]["zero"] == tc["zero"]
       and nc["triple"]["disjoint"] == tc["disjoint"] and nc["triple"]["total"] == math.comb(idx, 2)
       and ok_int_histogram(rk["new_triple_double_row_histogram"]) == th, (tc, th))
    qc, qh = census(rows, ((idx,) + c for c in itertools.combinations(range(idx), 3)))
    dj_unions = set()
    for c in itertools.combinations(range(idx), 3):
        if classify(rows, (idx,) + c) == "disjoint":
            u = set()
            for i in (idx,) + c:
                u |= set(rows[i])
            dj_unions.add(len(u))
    ck("k32_new_quad_census_disjoint_union_sizes",
       nc["quad"]["b_only"] == qc["b_only"] and nc["quad"]["zero"] == qc["zero"]
       and nc["quad"]["disjoint"] == qc["disjoint"] and nc["quad"]["total"] == math.comb(idx, 3)
       and ok_int_histogram(rk["new_quad_double_row_histogram"]) == qh
       and rk["disjoint_quad_count"] == qc["disjoint"] == 158
       and ok_int_histogram(rk["disjoint_quad_union_sizes"]) == {8: 158}
       and dj_unions == {8}, (qc, qh))
    dj32 = sum(1 for c in itertools.combinations(range(32), 4) if classify(rows, c) == "disjoint")
    dj31 = sum(1 for c in itertools.combinations(range(31), 4) if classify(rows, c) == "disjoint")
    ck("k32_cumulative_disjoint_quads_820_era_continuation_662",
       rk["cumulative_disjoint_quads"] == dj32 == 820
       and dj32 - qc["disjoint"] == dj31 == 662, (dj32, dj31))
    qtc, qth = census(rows, ((idx,) + c for c in itertools.combinations(range(idx), 4)))
    profiles = {}
    for c in itertools.combinations(range(idx), 4):
        combo = (idx,) + c
        if classify(rows, combo) != "b_only":
            continue
        pr = {"b_only": 0, "zero": 0, "disjoint": 0}
        for drop in range(5):
            pr[classify(rows, tuple(x for j, x in enumerate(combo) if j != drop))] += 1
        key = "%d/%d/%d" % (pr["b_only"], pr["disjoint"], pr["zero"])
        profiles[key] = profiles.get(key, 0) + 1
    ck("k32_new_quint_census_double_rows_profiles",
       nc["quint"]["b_only"] == qtc["b_only"] and nc["quint"]["zero"] == qtc["zero"]
       and nc["quint"]["disjoint"] == qtc["disjoint"] and nc["quint"]["total"] == math.comb(idx, 4)
       and ok_int_histogram(rk["new_quint_double_row_histogram"]) == qth
       and {str(k): v for k, v in rk["b_only_quint_four_subset_profiles"].items()} == profiles
       and set(profiles.keys()) == {"3/2/0"}, (qtc, qth, profiles))

    ftc, fth = census(rows, itertools.combinations(range(32), 3))
    pub_ft = rk["full_triples"]
    ck("k32_full_triple_census_C32_3",
       pub_ft["counts"] == ftc and pub_ft["total"] == 4960 and pub_ft["compared"] == 4960
       and pub_ft["mismatches"] == 0
       and ok_int_histogram(pub_ft["double_row_histogram"]) == fth, (ftc, fth))
    fqc, fqh = census(rows, itertools.combinations(range(32), 5))
    pub_fq = rk["full_quints"]
    st31 = k31["structure"]
    ck("k32_full_quint_census_C32_5_era_continuation_vs_k31",
       pub_fq["counts"] == fqc and pub_fq["total"] == 201376 and pub_fq["compared"] == 201376
       and pub_fq["mismatches"] == 0
       and ok_int_histogram(pub_fq["double_row_histogram"]) == fqh
       and fqc["b_only"] - qtc["b_only"] == st31["quint_census_k31"]["b_only"] == 6787
       and fqc["zero"] - qtc["zero"] == st31["quint_census_k31"]["zero"] == 163124,
       (fqc, fqh))
    sxc, _ = census(rows, itertools.combinations(range(32), 6))
    pub_sx = rk["sextet_census"]
    ck("k32_sextet_census_C32_6_all_zero",
       pub_sx["counts"] == sxc and sxc["zero"] == 906192 and sxc["b_only"] == 0
       and sxc["disjoint"] == 0 and pub_sx["total"] == 906192 and pub_sx["mismatches"] == 0)
    raw = fetch_bytes(*PINS["k32pre"], args.local).decode("utf-8")
    ck("k32_raw_json_exact_integer_serialization",
       str(M) in raw and str(A) in raw and str(B) in raw
       and isinstance(rk["membership"], int) and isinstance(rk["a_part"], int)
       and isinstance(rk["b_part"], int) and isinstance(json.loads(raw)["rank32"]["membership"], int))

    # ---- rank31_regression layer ------------------------------------
    rg = p["rank31_regression"]
    i31 = 30
    ck("k31reg_root_membership_exact_prior_hits",
       rg["root"] == top[i31]["root"] and int(rg["membership"]) == int(top[i31]["membership"])
       and ok_int_histogram(rg["prior_hits"]) == {r: len([i for i in range(i31) if r in rows[i]]) for r in rows[i31]},
       (rg["root"], int(rg["membership"])))
    rnc = rg["new_census"]
    pc31, _ = census(rows, [(i31, i) for i in range(i31)])
    tc31, th31 = census(rows, ((i31,) + c for c in itertools.combinations(range(i31), 2)))
    qc31, qh31 = census(rows, ((i31,) + c for c in itertools.combinations(range(i31), 3)))
    qtc31, qth31 = census(rows, ((i31,) + c for c in itertools.combinations(range(i31), 4)))
    ck("k31reg_new_censuses_all_four_layers",
       rnc["pair"]["b_only"] == pc31["b_only"] and rnc["pair"]["disjoint"] == pc31["disjoint"]
       and rnc["triple"]["b_only"] == tc31["b_only"] and rnc["triple"]["zero"] == tc31["zero"]
       and rnc["triple"]["disjoint"] == tc31["disjoint"]
       and rnc["quad"]["b_only"] == qc31["b_only"] and rnc["quad"]["zero"] == qc31["zero"]
       and rnc["quad"]["disjoint"] == qc31["disjoint"]
       and rnc["quint"]["b_only"] == qtc31["b_only"] and rnc["quint"]["zero"] == qtc31["zero"]
       and rnc["quint"]["disjoint"] == qtc31["disjoint"],
       (pc31, tc31, qc31, qtc31))
    ck("k31reg_new_double_row_histograms",
       ok_int_histogram(rg["new_triple_double_row_histogram"]) == th31
       and ok_int_histogram(rg["new_quad_double_row_histogram"]) == qh31
       and ok_int_histogram(rg["new_quint_double_row_histogram"]) == qth31,
       qth31)
    ftc31, fth31 = census(rows, itertools.combinations(range(31), 3))
    fqc31, fqh31 = census(rows, itertools.combinations(range(31), 5))
    sxc31, _ = census(rows, itertools.combinations(range(31), 6))
    ck("k31reg_full_censuses_and_k31_publication_match",
       rg["full_triples"]["counts"] == ftc31 == st31["triple_census_k31"]
       and rg["full_triples"]["total"] == 4495
       and ok_int_histogram(rg["full_triples"]["double_row_histogram"]) == fth31
       and rg["full_quints"]["counts"] == fqc31 == st31["quint_census_k31"]
       and rg["full_quints"]["total"] == 169911
       and ok_int_histogram(rg["full_quints"]["double_row_histogram"]) == fqh31
       and rg["sextet_census"]["counts"] == sxc31 and sxc31["zero"] == 736281,
       (ftc31, fqc31))
    # new pair/triple/quad/quint partners + full triple/quint + sextet
    cmb31 = sum([30, 435, 4060, 27405, 4495, 169911, 736281])
    ck("k31reg_classifier_comparisons_formula",
       rg["classifier_comparisons"] == cmb31 == 942617 and rg["mismatches"] == 0, cmb31)

    # ---- rank30_regression layer ------------------------------------
    r3 = p["rank30_regression"]
    i30 = 29
    ck("k30reg_root_membership_exact_prior_hits",
       r3["root"] == top[i30]["root"] and int(r3["membership"]) == int(top[i30]["membership"])
       and ok_int_histogram(r3["prior_hits"]) == {r: len([i for i in range(i30) if r in rows[i]]) for r in rows[i30]},
       (r3["root"], int(r3["membership"])))
    r3nc = r3["new_census"]
    pc30, _ = census(rows, [(i30, i) for i in range(i30)])
    tc30, th30 = census(rows, ((i30,) + c for c in itertools.combinations(range(i30), 2)))
    qc30, qh30 = census(rows, ((i30,) + c for c in itertools.combinations(range(i30), 3)))
    qtc30, qth30 = census(rows, ((i30,) + c for c in itertools.combinations(range(i30), 4)))
    ck("k30reg_new_censuses_all_four_layers",
       r3nc["pair"]["b_only"] == pc30["b_only"] and r3nc["pair"]["disjoint"] == pc30["disjoint"]
       and r3nc["triple"]["b_only"] == tc30["b_only"] and r3nc["triple"]["zero"] == tc30["zero"]
       and r3nc["triple"]["disjoint"] == tc30["disjoint"]
       and r3nc["quad"]["b_only"] == qc30["b_only"] and r3nc["quad"]["zero"] == qc30["zero"]
       and r3nc["quad"]["disjoint"] == qc30["disjoint"]
       and r3nc["quint"]["b_only"] == qtc30["b_only"] and r3nc["quint"]["zero"] == qtc30["zero"]
       and r3nc["quint"]["disjoint"] == qtc30["disjoint"],
       (pc30, tc30, qc30, qtc30))
    ck("k30reg_new_double_row_histograms",
       ok_int_histogram(r3["new_triple_double_row_histogram"]) == th30
       and ok_int_histogram(r3["new_quad_double_row_histogram"]) == qh30
       and ok_int_histogram(r3["new_quint_double_row_histogram"]) == qth30,
       qth30)
    ftc30, fth30 = census(rows, itertools.combinations(range(30), 3))
    fqc30, fqh30 = census(rows, itertools.combinations(range(30), 5))
    sxc30, _ = census(rows, itertools.combinations(range(30), 6))
    ck("k30reg_full_censuses_C30_3_5_6",
       r3["full_triples"]["counts"] == ftc30 and r3["full_triples"]["total"] == 4060
       and ok_int_histogram(r3["full_triples"]["double_row_histogram"]) == fth30
       and r3["full_quints"]["counts"] == fqc30 and r3["full_quints"]["total"] == 142506
       and ok_int_histogram(r3["full_quints"]["double_row_histogram"]) == fqh30
       and r3["sextet_census"]["counts"] == sxc30 and sxc30["zero"] == 593775,
       (ftc30, fqc30))
    # era continuity for the regression chain: full(31) - new(31) = full(30)
    ck("k30_to_k31_to_k32_era_b_only_continuity",
       fqc31["b_only"] - qtc31["b_only"] == fqc30["b_only"]
       and fqc["b_only"] - qtc["b_only"] == fqc31["b_only"]
       and ftc31["b_only"] - tc31["b_only"] == ftc30["b_only"]
       and ftc["b_only"] - tc["b_only"] == ftc31["b_only"],
       (ftc30["b_only"], ftc31["b_only"], ftc["b_only"],
        fqc30["b_only"], fqc31["b_only"], fqc["b_only"]))

    n_fail = sum(0 if good else 1 for _, good in checks)
    for name, good in checks:
        if not good:
            print(f"  -> failed: {name}")
    print(f"--- {len(checks)} verification checks, {n_fail} failures")
    return 0 if n_fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
