#!/usr/bin/env python3
"""Membership / elimination / joint-membership analysis for the second-cheapest
cover target, parent 00000000000000821082000000000000 (18 open non-STERILE S6
rows, published exact minimum cover cost 9, method perfect_matching).

With maxspan = 2 and r = 18 even, every minimum cover of size 9 is exactly a
perfect matching of the 18 rows by pair roots (a cover with s singleton-span
roots and p pair-span roots needs s + p = 9 roots and s + 2p >= 18 covered
slots, forcing s = 0). Hence, with edge multiplicities w(a,b) = number of
distinct pair roots covering exactly rows {a,b}:
  - total minimum covers = weighted perfect matching count pm(V),
  - membership of a pair root on {a,b} = pm(V \\ {a,b})   [root fixed, rest
    matched arbitrarily],
  - singleton-span roots have membership 0 (checked, not assumed),
  - banning a set S of roots = decrementing multiplicities and recomputing
    pm (exact survival curve),
  - joint membership of roots on disjoint pairs = pm(V minus both pairs),
    0 on the same pair (a 9-root cover cannot contain two roots spanning the
    same pair: 18 slots with one pair double-covered leaves 16 rows for 7
    roots, impossible).
Identity: sum of memberships over all distinct roots == 9 * pm(V).

All inputs are published pins; the candidate-root JSONL is regenerated by the
published phase-1 script enumerate_global_candidate_roots_20261118.py from
exactly those pins (deterministic), and this script cross-checks every
aggregate (rows, candidates, distinct roots, span histogram) against the
published per-parent cover-cost table entry.
"""
import json, os, sys, hashlib
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
N = 11
PARENT = "00000000000000821082000000000000"

def git_blob_sha(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\x00" % len(data) + data).hexdigest()

def read_pinned(rel, pin):
    with open(os.path.join(ROOT, rel), "rb") as f:
        data = f.read()
    if git_blob_sha(data) != pin:
        raise SystemExit("pin mismatch: " + rel)
    return data

T = [
    lambda x, y: (x, y),
    lambda x, y: (y, N - 1 - x),
    lambda x, y: (N - 1 - x, N - 1 - y),
    lambda x, y: (N - 1 - y, x),
    lambda x, y: (N - 1 - x, y),
    lambda x, y: (x, N - 1 - y),
    lambda x, y: (y, x),
    lambda x, y: (N - 1 - y, N - 1 - x),
]
TO = [tuple(t(i % N, i // N) for i in range(121)) for t in T]

def orbit_masks(mask):
    """All 8 transformed masks of a state (as integers)."""
    outs = []
    for to in TO:
        out = 0
        for i in range(121):
            if (mask >> i) & 1:
                qx, qy = to[i]
                out |= 1 << (qy * N + qx)
        outs.append(out)
    return outs

def pm_count(rows_bit, edge_mult, anchor="low"):
    """Weighted perfect matching count over row indices, with multiplicities
    edge_mult[(a,b)] (a<b). Iterative DP over submasks reachable by removing
    positive-weight pairs, processed in increasing popcount order. anchor
    selects which set bit is matched first ("low" or "high"); both orders must
    yield the same total (independent arithmetic path cross-check)."""
    memo = {0: 1}
    full = rows_bit
    order = []
    stack = [full]
    seen = {full}
    while stack:
        m = stack.pop()
        order.append(m)
        if m == 0:
            continue
        if anchor == "low":
            first = (m & -m).bit_length() - 1
        else:
            first = m.bit_length() - 1
        rest = m & ~(1 << first)
        mm = rest
        while mm:
            j = (mm & -mm).bit_length() - 1
            mm &= mm - 1
            key = (first, j) if first < j else (j, first)
            if edge_mult.get(key, 0):
                sub = rest & ~(1 << j)
                if sub not in seen:
                    seen.add(sub)
                    stack.append(sub)
    for m in sorted(order, key=lambda x: bin(x).count("1")):
        if m == 0:
            continue
        if anchor == "low":
            first = (m & -m).bit_length() - 1
        else:
            first = m.bit_length() - 1
        rest = m & ~(1 << first)
        total = 0
        mm = rest
        while mm:
            j = (mm & -mm).bit_length() - 1
            mm &= mm - 1
            key = (first, j) if first < j else (j, first)
            w = edge_mult.get(key, 0)
            if w:
                total += w * memo[rest & ~(1 << j)]
        memo[m] = total
    return memo[full], memo

def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        HERE, "output", "cost9-parent-membership-and-elimination-20261118.json")
    checks = []
    def check(name, ok, detail=""):
        checks.append({"name": name, "pass": bool(ok),
                       "detail": detail if isinstance(detail, str) else json.dumps(detail)})

    # published inputs (pins verified on read)
    wl = read_pinned("research/experiments/n11-class2-lane-closability-ranking-20261116/output/class-frontier-remaining-s6-worklist-1410-20261116.csv",
                     "2fee1d0718547a62e346d35f5858d7913e37c097").decode().rstrip("\r\n").split("\n")
    headers = [h.strip() for h in wl[0].split(",")]
    worklist_hexes = set()
    for line in wl[1:]:
        vals = line.split(",")
        r = {h: (vals[i].strip() if i < len(vals) else "") for i, h in enumerate(headers)}
        worklist_hexes.add(r["s6_canonical_hex"])
    read_pinned("research/experiments/n11-head1410-receipt-unclosability-census-20261116/output/n11-head1410-receipt-unclosability-census-20261116.json",
                "9c251da3138c5cb0516e097be5e5d0427dfaf5f0")
    read_pinned("research/experiments/n11-head1410-partial-parent-nonsterile-children-20261118/output/fold-chain-ledger-1410-1476-crosscheck-20261118.json",
                "e8785d509e8a11a37c0d03cc450455a14708c34d")
    table = json.loads(read_pinned("research/experiments/n11-head1410-partial-parent-nonsterile-children-20261118/output/parent-minimum-cover-cost-table-20261118.json",
                                   "4e4a911d0e05779437d4a8e97685a8feb66c0d25"))
    tbl = {e["hex"]: e for e in table["derived"]["table"]}[PARENT]

    # candidate roots per row (regenerable via published phase-1 script)
    row_cands = {}
    with open(os.path.join(HERE, "output", "global-candidate-roots-20261118.jsonl")) as f:
        for line in f:
            e = json.loads(line)
            row_cands[e["row"]] = e
    # the JSONL holds exactly the open non-STERILE rows (6,337); the cover
    # table's rows_total (12,052) additionally counts STERILE rows and is not
    # comparable here.
    check("jsonl.rows_total_open_nonsterile", len(row_cands) == 6337, len(row_cands))
    check("jsonl.rows_in_worklist", all(h in worklist_hexes for h in row_cands))

    # target rows: children of PARENT (parent + one stone), via orbit set
    p_orbit = {format(m, "032x") for m in orbit_masks(int(PARENT, 16))}
    target = sorted(h for h in row_cands
                    if any(format(int(h, 16) ^ (1 << b), "032x") in p_orbit
                           for b in range(121) if (int(h, 16) >> b) & 1))
    check("target.rows", len(target) == tbl["rows_r"] == 18, len(target))
    check("table.exact9", tbl["exact"] and tbl["witness_size"] == 9 and tbl["lower_bound"] == 9)

    idx = {h: i for i, h in enumerate(target)}
    proot_rows = defaultdict(set)
    cand_total = 0
    for h in target:
        e = row_cands[h]
        cand_total += e["cost"]
        for root, bit in e["cands"]:
            proot_rows[root].add(h)
    check("candidates", cand_total == tbl["candidates"] == 1238, cand_total)
    check("distinct_roots", len(proot_rows) == tbl["distinct_roots"] == 687, len(proot_rows))
    hist = defaultdict(int)
    for root, cov in proot_rows.items():
        hist[len(cov)] += 1
    check("span_histogram", {str(k): v for k, v in sorted(hist.items())} == tbl["span_histogram"],
          dict(hist))
    check("maxspan2", max(hist) == 2 and tbl["maxspan"] == 2)

    pair_roots = defaultdict(list)  # (a,b) row-index pair (a<b) -> root hexes
    singleton_roots = []
    for root, cov in proot_rows.items():
        if len(cov) == 2:
            a, b = sorted(idx[h] for h in cov)
            pair_roots[(a, b)].append(root)
        else:
            singleton_roots.append(root)
    edge_mult = {e: len(rl) for e, rl in pair_roots.items()}
    root_pair = {root: e for e, rl in pair_roots.items() for root in rl}
    check("singleton_roots", len(singleton_roots) == hist[1] == 136, len(singleton_roots))
    check("pair_roots", sum(len(v) for v in pair_roots.values()) == hist[2] == 551)
    check("pair_types", len(pair_roots) <= 153)

    full = (1 << 18) - 1
    total, memo = pm_count(full, edge_mult)
    total_high, _ = pm_count(full, edge_mult, anchor="high")
    check("total.anchor_independence", total == total_high,
          {"low": str(total), "high": str(total_high)})
    check("total_positive", total > 0, str(total))

    # membership: pair roots anchored at row 0 read pm(V\\e) from the memo;
    # all others are computed by a standalone DP on the 16-row remainder
    # (same semantics: matchings of V\\e with root choice for e fixed)
    membership = {}
    standalone = 0
    for (a, b), rl in pair_roots.items():
        rest = full & ~((1 << a) | (1 << b))
        if rest in memo:
            val = memo[rest]
        else:
            val, _ = pm_count(rest, edge_mult)
            standalone += 1
        for root in rl:
            membership[root] = val
    for root in singleton_roots:
        membership[root] = 0
    check("membership.standalone_dp_pairs", standalone <= len(pair_roots), standalone)
    total_membership = sum(membership.values())
    check("membership.identity_9x", total_membership == 9 * total,
          {"sum": str(total_membership), "9x": str(9 * total)})
    zero_mem = [r for r, m in membership.items() if m == 0]
    check("membership.zero_are_singletons", all(m in singleton_roots for m in zero_mem),
          {"zero_count": len(zero_mem), "singleton_count": len(singleton_roots)})

    # published witness crosscheck: the table's 9 witness roots are a perfect
    # matching, each with membership > 0
    wit = tbl["witness_roots"]
    wit_cov = defaultdict(set)
    for root in wit:
        for h in proot_rows[root]:
            wit_cov[root].add(h)
    wit_rows = set()
    for root in wit:
        wit_rows |= wit_cov[root]
    check("witness.covers_all", wit_rows == set(target) and len(wit) == 9)
    check("witness.pair_spans", all(len(wit_cov[r]) == 2 for r in wit))
    check("witness.disjoint", sum(len(wit_cov[r]) for r in wit) == 18)
    check("witness.membership_positive", all(membership[r] > 0 for r in wit),
          {r: str(membership[r]) for r in wit})

    # survival curve: ban top-k roots by membership (deterministic order)
    by_mem = sorted([r for r in membership if membership[r] > 0],
                    key=lambda r: (-membership[r], r))
    TOPK = 12
    survival = []
    prev_killed = 0
    banned = set()
    for k in range(0, TOPK + 1):
        if k > 0:
            banned.add(by_mem[k - 1])
        em = dict(edge_mult)
        for root in banned:
            for e, rl in pair_roots.items():
                if root in rl:
                    em[e] -= 1
        rem, _ = pm_count(full, em)
        killed = total - rem
        survival.append({
            "k": k,
            "banned_root": by_mem[k] if k < TOPK else None,
            "surviving_covers": rem,
            "killed_covers": killed,
            "killed_share": (killed / total if total else 0),
            "marginal_kill": killed - prev_killed,
        })
        prev_killed = killed
    check("survival.k1_kill_equals_membership",
          survival[1]["marginal_kill"] == membership[by_mem[0]],
          {"marginal": str(survival[1]["marginal_kill"]),
           "membership": str(membership[by_mem[0]])})
    check("survival.monotone",
          all(survival[k]["surviving_covers"] <= survival[k - 1]["surviving_covers"]
              for k in range(1, TOPK + 1)))

    # joint membership for the top-10 (from the same memo)
    top10 = by_mem[:10]
    joint = []
    for i in range(len(top10)):
        for j in range(i + 1, len(top10)):
            ri, rj = top10[i], top10[j]
            ei = root_pair[ri]
            ej = root_pair[rj]
            if set(ei) & set(ej):
                # same pair, or two pairs sharing a row: impossible in a
                # perfect matching, joint membership is exactly 0
                m_ij = 0
            else:
                rest = full & ~((1 << ei[0]) | (1 << ei[1]) | (1 << ej[0]) | (1 << ej[1]))
                m_ij = memo.get(rest)
                if m_ij is None:
                    m_ij, _ = pm_count(rest, edge_mult)
            joint.append({"a": ri, "b": rj,
                          "pair_a": list(ei), "pair_b": list(ej),
                          "membership_a": membership[ri], "membership_b": membership[rj],
                          "joint_membership": m_ij})
    check("joint.bounded",
          all(e["joint_membership"] <= min(e["membership_a"], e["membership_b"]) for e in joint))
    check("joint.row_sharing_pairs_zero",
          all(e["joint_membership"] == 0
              for e in joint if set(e["pair_a"]) & set(e["pair_b"])))

    all_pass = all(c["pass"] for c in checks)
    output = {
        "schema": "n11-cost9-parent-membership-and-elimination-20261118-v1",
        "date": "2026-11-18",
        "lane": "n11 long lane (verification side)",
        "title": ("Membership, elimination survival and joint membership for the 18-row "
                  "cover problem of parent 00000000000000821082000000000000 (exact cost 9, "
                  "second-cheapest of the 174 open-parent cover targets)"),
        "inputs": {
            "worklist": {"path": "research/experiments/n11-class2-lane-closability-ranking-20261116/output/class-frontier-remaining-s6-worklist-1410-20261116.csv",
                          "git_blob_sha1": "2fee1d0718547a62e346d35f5858d7913e37c097"},
            "census": {"path": "research/experiments/n11-head1410-receipt-unclosability-census-20261116/output/n11-head1410-receipt-unclosability-census-20261116.json",
                        "git_blob_sha1": "9c251da3138c5cb0516e097be5e5d0427dfaf5f0"},
            "ledger": {"path": "research/experiments/n11-head1410-partial-parent-nonsterile-children-20261118/output/fold-chain-ledger-1410-1476-crosscheck-20261118.json",
                        "git_blob_sha1": "e8785d509e8a11a37c0d03cc450455a14708c34d"},
            "cover_table": {"path": "research/experiments/n11-head1410-partial-parent-nonsterile-children-20261118/output/parent-minimum-cover-cost-table-20261118.json",
                             "git_blob_sha1": "4e4a911d0e05779437d4a8e97685a8feb66c0d25"},
            "candidate_roots": {"path": "(regenerated) output/global-candidate-roots-20261118.jsonl",
                                 "regenerated_by": "enumerate_global_candidate_roots_20261118.py",
                                 "note": ("deterministic from the four pinned inputs; all "
                                          "aggregates cross-checked against the published "
                                          "table entry")}},
        "method": ("With maxspan=2 and r=18 even, every size-9 cover is a perfect "
                   "matching by pair roots (s+p=9, s+2p>=18 forces s=0), so exact "
                   "counting reduces to one weighted perfect-matching DP over 2^18 row "
                   "masks. Membership of a pair root on {a,b} = pm(V\\{a,b}) read from "
                   "the same memo; singleton-span roots have membership 0; banning "
                   "roots = multiplicity decrement + DP recompute (exact survival "
                   "curve); joint membership of roots on disjoint pairs = pm(V minus "
                   "both pairs), 0 on the same pair."),
        "derived": {
            "rows": 18,
            "candidates": cand_total,
            "distinct_roots": len(proot_rows),
            "span_histogram": {str(k): v for k, v in sorted(hist.items())},
            "pair_types": len(pair_roots),
            "pair_multiplicity_histogram": {str(k): sum(1 for e in pair_roots.values() if len(e) == k)
                                             for k in sorted({len(e) for e in pair_roots.values()})},
            "membership_standalone_dp_pairs": standalone,
            "membership_nonzero_stats": {
                "count": sum(1 for v in membership.values() if v > 0),
                "min": min(v for v in membership.values() if v > 0),
                "max": max(membership.values()),
            },
            "total_minimum_covers": total,
            "per_pair_multiplicity": {"%d,%d" % ab: len(rl)
                                        for ab, rl in sorted(pair_roots.items())},
            "membership": {r: membership[r] for r in sorted(membership)},
            "top50_by_membership": [
                {"root": r, "membership": membership[r],
                 "pair_row_indices": list(root_pair[r]),
                 "pair_rows": [target[root_pair[r][0]], target[root_pair[r][1]]]}
                for r in by_mem[:50]],
            "survival_curve_banning_topk": survival,
            "top10_joint_membership": joint,
        },
        "checks": checks,
        "check_count": len(checks),
        "all_pass": all_pass,
        "interpretation_guard": ("Cover-plan combinatorics only. Membership counts the "
                                 "number of alternative 9-root cover plans a root "
                                 "participates in; it is not a search cost and implies "
                                 "nothing about WIN/REFUTED outcomes of any root. "
                                 "REFUTED-D10 and STERILE are not LOSS proofs."),
        "unknown_status": ("Standard 11x11 empty board, two-stone roots {49,60}/{59,60}, "
                           "S2 {59,60}, and classes 1/2/4 remain UNKNOWN."),
    }
    with open(out_path, "w") as f:
        f.write(json.dumps(output, indent=2) + "\n")
    print(json.dumps({"out": out_path, "all_pass": all_pass, "checks": len(checks),
                      "failed": [c["name"] for c in checks if not c["pass"]][:10],
                      "total_covers": total,
                      "top3": [{"root": r, "membership": membership[r]} for r in by_mem[:3]],
                      "survival_head": survival[:6],
                      "joint_top": sorted(joint, key=lambda e: -e["joint_membership"])[:5],
                      "pair_types": len(pair_roots)},
                     indent=1))
    if not all_pass:
        sys.exit(1)

if __name__ == "__main__":
    main()
