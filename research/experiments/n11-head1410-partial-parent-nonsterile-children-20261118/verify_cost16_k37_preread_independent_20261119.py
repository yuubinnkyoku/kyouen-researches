def git_blob_sha1(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\x00" % len(data) + data).hexdigest()


def fetch_bytes(name: str, want_sha: str, local_dir: str | None) -> bytes:
    if local_dir:
        data = open(f"{local_dir}/{name}", "rb").read()
    else:
        urls = [
            f"https://cdn.jsdelivr.net/gh/{REPO}@main/{PATH}/{name}",
            f"https://raw.githubusercontent.com/{REPO}/main/{PATH}/{name}",
        ]
        data = None
        shas = []
        for u in urls:
            try:
                data = urllib.request.urlopen(u, timeout=60).read()
            except Exception:
                continue
            got = git_blob_sha1(data)
            if got == want_sha:
                break
            shas.append((u.split("/")[2], got))
            data = None
        if data is None:
            raise RuntimeError(f"could not fetch {name} at pinned sha "
                               f"{want_sha} (mirror results: {shas})")
        return data
    got = git_blob_sha1(data)
    if got != want_sha:
        raise RuntimeError(f"{name}: blob sha1 {got} != pinned {want_sha}")
    return data


def fetch(name: str, want_sha: str, local_dir: str | None) -> dict:
    return json.loads(fetch_bytes(name, want_sha, local_dir))


# ---- second-lineage engine: bit-mask row multiplicity ---------------
# row r <-> bit r.  d2 = OR of pairwise mask intersections (rows covered
# by >= 2 roots of the combo); d3 = OR of triplewise intersections (rows
# covered by >= 3).  disjoint <=> d2 == 0; b_only <=> d3 == 0 and exactly
# one doubled row; zero otherwise.  This is a different code path from
# the dict-accumulate/Counter lineage of the preread scripts.
def classify_mask(combo, MK):
    ms = [MK[i] for i in combo]
    L = len(ms)
    d2 = ms[0] & ms[1]
    for a in range(2, L):
        ma = ms[a]
        for b in range(a):
            d2 |= ma & ms[b]
    if d2 == 0:
        return "disjoint", None
    d3 = 0
    for a in range(L):
        ma = ms[a]
        for b in range(a):
            mab = ma & ms[b]
            if mab:
                for c in range(b):
                    d3 |= mab & ms[c]
    if d3:
        return "zero", None
    if d2.bit_count() >= 2:
        return "zero", None
    return "b_only", d2.bit_length() - 1


# ---- independent Counter variant for the engine-agreement spot check
def classify_counter(combo, rows):
    c = {}
    for i in combo:
        for r in rows[i]:
            c[r] = c.get(r, 0) + 1
    twos = [r for r, v in c.items() if v == 2]
    if any(v >= 3 for v in c.values()) or len(twos) > 1:
        return "zero", None
    if len(twos) == 1:
        return "b_only", twos[0]
    return "disjoint", None


def census_mask(combos, MK):
    out = {"b_only": 0, "zero": 0, "disjoint": 0}
    hist = {}
    for combo in combos:
        cl, row = classify_mask(combo, MK)
        out[cl] += 1
        if cl == "b_only":
            hist[row] = hist.get(row, 0) + 1
    return out, dict(sorted(hist.items()))


def disjoint_global(n, MK):
    return sum(1 for c in itertools.combinations(range(n), 4)
               if classify_mask(c, MK)[0] == "disjoint")


def disjoint_union_sizes(idx, rows, MK):
    dus = {}
    for c in itertools.combinations(range(idx), 3):
        combo = (idx,) + c
        if classify_mask(combo, MK)[0] == "disjoint":
            u = set()
            for i in combo:
                u |= set(rows[i])
            dus[len(u)] = dus.get(len(u), 0) + 1
    return dict(sorted(dus.items()))


def quint_profiles(idx, rows, MK):
    profiles = {}
    for c in itertools.combinations(range(idx), 4):
        combo = (idx,) + c
        if classify_mask(combo, MK)[0] != "b_only":
            continue
        pr = {"b_only": 0, "zero": 0, "disjoint": 0}
        for drop in range(5):
            pr[classify_mask(tuple(x for j, x in enumerate(combo) if j != drop), MK)[0]] += 1
        key = "%d/%d/%d" % (pr["b_only"], pr["disjoint"], pr["zero"])
        profiles[key] = profiles.get(key, 0) + 1
    return dict(sorted(profiles.items()))


def ok_int_histogram(d) -> dict:
    return {int(k): v for k, v in d.items()}


def pair_dict(d) -> dict:
    """normalize the pair census spelling (shared vs b_only)."""
    out = {"b_only": int(d.get("shared", d.get("b_only", 0))),
           "zero": int(d.get("zero", 0)),
           "disjoint": int(d["disjoint"])}
    return out


