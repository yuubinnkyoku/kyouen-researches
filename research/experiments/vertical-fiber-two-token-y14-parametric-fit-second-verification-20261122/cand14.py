    tail = x % 2 == 1 and R >= x + z + Y + 1
    if z % 2 == 1:
        if -Y <= d <= Y and d % 2 == 0:
            k = (d + 3 * Y + 2) // 4           # I rows: pin-parity rows (d == 2 mod 4, incl. diagonal d == -Y)
