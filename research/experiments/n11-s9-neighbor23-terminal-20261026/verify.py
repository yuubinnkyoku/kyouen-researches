#!/usr/bin/env python3
"""N11 S9 AND certificate: 23 new first-player WIN roots.

The proof independently enumerates all legal S10 children using two exact
integer geometries, then solves every child to terminal. Each geometry has
its own transposition table; only terminal minimax values are memoized.
The shared table across S10 leaves is an optimization, not an input verdict
cache. Neither solver imports precomputed game outcomes.
"""
import argparse
import hashlib
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent
ROOT_HASH = '7e99cd0c2a92410569382afd50ec9ac791bbd33d798560b7bd341b2a5621dff1'
LEAF_HASH = '63a5b47c00bd4c9cf5d6aae26191372317963c430799343bb859a9fe140b79c7'
PARENT_HASH = '298c2831090369f799a839b250f3575802b3d6707466d30a343f14d14e2fd1d5'
STATE_HASH = 'd95e59c083e6a4aec0c5d367b74e3a66e682a88f4e5cb13ee3215860f3721592'


def need(ok, message):
    if not ok:
        raise ValueError(message)


def load_module(name, filename):
    spec = importlib.util.spec_from_file_location(name, filename)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


THREE = load_module('n11_neighbor23_three',
                    EXP / 'n11-s9-terminal-neighbor-20261025' / 'verify.py')
FOUR = load_module('n11_neighbor23_four',
                   EXP / 'n11-batch-s9-terminal-20261025' / 'verify.py')


def digest(values):
    return hashlib.sha256(''.join(f'{v:032x}\n' for v in sorted(values))
                          .encode('ascii')).hexdigest()


def roots_from_file():
    raw = (HERE / 's9-roots.keys').read_bytes()
    need(hashlib.sha256(raw).hexdigest() == ROOT_HASH,
         'S9 source file digest mismatch')
    lines = raw.decode('ascii').splitlines()
    need(len(lines) == 23 and lines == sorted(set(lines)),
         'missing/duplicate/unsorted S9 root')
    need(all(len(h) == 32 and set(h) <= set('0123456789abcdef')
             for h in lines), 'invalid S9 hexadecimal root')
    return [int(h, 16) for h in lines]


def children(geometry, board):
    legal = geometry.legal(board)
    return {geometry.canonical(board | (1 << p))
            for p in range(121) if legal >> p & 1}


def boundary(roots, leaves, parents):
    """Reject altered boundaries independently of the terminal solvers."""
    need(len(roots) == 23 and len(leaves) == 457 and len(parents) == 192,
         'S9/S10/S8 certificate boundary size changed')
    for items, count in ((roots, 9), (leaves, 10), (parents, 8)):
        need(len(items) == len(set(items)), 'duplicate certificate key')
        for board in items:
            need(board.bit_count() == count, 'incorrect certificate stone count')
    need(digest(roots) == ROOT_HASH and digest(leaves) == LEAF_HASH
         and digest(parents) == PARENT_HASH,
         'S9/S10/S8 certificate boundary digest mismatch')
    for geometry in (THREE, FOUR):
        actual_leaves = set()
        actual_parents = set()
        incidences = 0
        for root in roots:
            need(geometry.safe(root) and geometry.canonical(root) == root,
                 'unsafe or noncanonical S9 root')
            child = children(geometry, root)
            incidences += len(child)
            actual_leaves.update(child)
            actual_parents.update(geometry.canonical(root ^ (1 << p))
                                  for p in geometry.points(root))
        need(incidences == 500 and actual_leaves == set(leaves),
             'S9 universal S10 boundary incomplete')
        need(actual_parents == set(parents),
             'S8 reverse-witness boundary incomplete')
        for parent in parents:
            need(geometry.safe(parent) and geometry.canonical(parent) == parent,
                 'unsafe or noncanonical S8 parent')
            # Every parent was generated by deleting one stone from a safe
            # S9 root. Restoring that stone is therefore a legal witness.
        for leaf in leaves:
            need(geometry.safe(leaf) and geometry.canonical(leaf) == leaf,
                 'unsafe or noncanonical S10 leaf')


def terminal_solver(geometry):
    """Independent exact minimax with a reusable, initially EMPTY table.

    The number reported for each leaf is the count of newly proved states;
    it is not a game length or an estimate of remaining proof distance.
    """
    memo = {}

    def visit(board):
        if board in memo:
            return memo[board]
        legal = geometry.legal(board)
        while legal:
            bit = legal & -legal
            legal -= bit
            if not visit(board | bit):
                memo[board] = True
                return True
        memo[board] = False
        return False

    def solve(board):
        before = len(memo)
        outcome = visit(board)
        return outcome, len(memo) - before

    return solve


def verify(negative=False):
    roots = roots_from_file()
    leaves = set()
    parents = set()
    for root in roots:
        leaves.update(children(THREE, root))
        parents.update(THREE.canonical(root ^ (1 << p))
                       for p in THREE.points(root))
    boundary(roots, sorted(leaves), sorted(parents))
    if negative:
        r, l, p = roots, sorted(leaves), sorted(parents)
        tests = ((r[:-1], l, p), (r, l[:-1], p), (r, l, p[:-1]),
                 (r, [l[0]] + l[:-1], p), (r, l, [p[0]] + p[:-1]))
        for changed in tests:
            try:
                boundary(*changed)
            except ValueError:
                continue
            raise ValueError('tampered S9 certificate accepted')
    solve3, solve4 = terminal_solver(THREE), terminal_solver(FOUR)
    state_rows = []
    total3 = total4 = 0
    for leaf in sorted(leaves):
        verdict3, count3 = solve3(leaf)
        verdict4, count4 = solve4(leaf)
        need(verdict3 and verdict4, f'non-WIN S10 terminal leaf: {leaf:032x}')
        need(count3 == count4, f'independent search mismatch: {leaf:032x}')
        legal3, legal4 = THREE.legal(leaf), FOUR.legal(leaf)
        need(legal3 == legal4, f'independent legal moves disagree: {leaf:032x}')
        total3 += count3
        total4 += count4
        state_rows.append(f'{leaf:032x} {count3} {legal3.bit_count()}\n')
    need(hashlib.sha256(''.join(state_rows).encode('ascii')).hexdigest()
         == STATE_HASH, 'per-leaf terminal search fingerprint changed')
    need(total3 == total4 == 32544, 'terminal state-count regression')
    print('VERIFIED N11: 23 S9 original-first WIN roots, 500 legal S10 '
          'incidences, 457 distinct terminal S10 WIN leaves, '
          '192 S8 witness parents, 32544 states per independent solver; '
          'empty=UNKNOWN')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--negative', action='store_true')
    verify(ap.parse_args().negative)
