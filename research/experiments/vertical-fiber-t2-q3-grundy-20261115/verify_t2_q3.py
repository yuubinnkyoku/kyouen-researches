#!/usr/bin/env python3
"""Exact Grundy audit for the pure t=2, q=3 fiber game.

Only the Python standard library is used. Safe vectors are generated by a
bounded-capacity recursion, independently of the proposed Grundy formula.
"""
from __future__ import annotations

from functools import lru_cache
import json


def safe_states(w: int, m: int):
    """Enumerate all labelled c in {0,...,m}^w with sum min(c_i,2) <= 2."""
    def visit(prefix, index, remaining):
        if index == w:
            yield tuple(prefix)
            return
        for value in range(m + 1):
            cost = min(value, 2)
            if cost <= remaining:
                prefix.append(value)
                yield from visit(prefix, index + 1, remaining - cost)
                prefix.pop()
    yield from visit([], 0, 2)


def grundy_function(m: int):
    @lru_cache(maxsize=None)
    def grundy(state):
        options = set()
        for i, value in enumerate(state):
            if value == m:
                continue
            child = list(state)
            child[i] += 1
            child = tuple(child)
            if sum(min(x, 2) for x in child) <= 2:
                options.add(grundy(child))
        mex = 0
        while mex in options:
            mex += 1
        return mex
    return grundy


def closed_form(state, m: int):
    occupied = [i for i, value in enumerate(state) if value]
    if not occupied:
        return 0
    if len(occupied) == 1:
        value = state[occupied[0]]
        if value >= 2:
            return (m - value) % 2
        return 1 if m % 2 == 0 else 2
    if len(occupied) == 2 and all(state[i] == 1 for i in occupied):
        return 0
    raise AssertionError(f"unexpected safe-state shape: {state}")


def audit():
    records = []
    total_states = 0
    nimbers = set()
    for w in range(2, 13):
        for m in range(2, 13):
            states = list(safe_states(w, m))
            state_set = set(states)
            expected_count = 1 + w * m + w * (w - 1) // 2
            if len(states) != expected_count or len(state_set) != len(states):
                raise AssertionError("safe-state census count/uniqueness failure")
            grundy = grundy_function(m)
            local_nimbers = set()
            for state in states:
                actual = grundy(state)
                predicted = closed_form(state, m)
                if actual != predicted:
                    raise AssertionError(
                        f"mismatch w={w} m={m} state={state}: "
                        f"mex={actual}, formula={predicted}"
                    )
                local_nimbers.add(actual)
                for i, value in enumerate(state):
                    if value == m:
                        continue
                    child = list(state)
                    child[i] += 1
                    child = tuple(child)
                    if sum(min(x, 2) for x in child) <= 2 and child not in state_set:
                        raise AssertionError(f"safe child omitted: {child}")
            records.append({
                "w": w,
                "m": m,
                "safe_states": len(states),
                "grundy_values": sorted(local_nimbers),
                "mismatches": 0,
            })
            total_states += len(states)
            nimbers.update(local_nimbers)
    return {
        "scope": {
            "rule": "pure fiber game; t=2; q=3; no base-trace constraints",
            "w_range": [2, 12],
            "m_range": [2, 12],
            "parameter_pairs": len(records),
        },
        "result": {
            "safe_state_instances_checked": total_states,
            "distinct_grundy_values": sorted(nimbers),
            "mismatches": 0,
        },
        "records": records,
    }


if __name__ == "__main__":
    print(json.dumps(audit(), ensure_ascii=False, separators=(",", ":"), sort_keys=True))
