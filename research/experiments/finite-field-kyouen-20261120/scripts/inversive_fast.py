"""Fast inversive-plane builder for arbitrary prime-power order q.

Why this file exists
--------------------
`inversive_all_q.build_inversive_plane` enumerates all triples of points to
find the circles, which costs O(n^3) Moebius evaluations.  For q = 13 that is
already 4.9e6 triples and for q >= 17 it is hopeless.

The circles of the inversive plane of order q are exactly the images of the
base circle  P^1(F_q) = F_q u {infinity}  under the group PGL(2, F_{q^2}).
That group is generated by the three maps

    T1: z |-> z + 1
    T2: z |-> lam * z      (lam a primitive element of F_{q^2})
    T3: z |-> 1 / z

so a BFS over the orbit of the base circle produces every circle after
exactly q(q^2+1) steps, each of which costs (q+1) Moebius evaluations.

The base circle is emitted first (index 0) because several C programs in this
directory assume that convention.

Run
---
    python inversive_fast.py --q 11 13 17          # just verify counts
    python inversive_fast.py --q 13 --export       # also write circles_q13.txt
    python inversive_fast.py --q 3 4 5 7 8 9 --crosscheck
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from inversive_all_q import build_field  # noqa: E402


# ---------------------------------------------------------------------------
# Moebius action on P^1(F)
# ---------------------------------------------------------------------------

def make_inverse_table(F) -> dict:
    """element -> inverse, computed once (F.inv is a pow and very slow)."""
    tab = {}
    for x in F.elements():
        if not F.is_zero(x):
            tab[x] = F.inv(x)
    return tab


def apply_matrix(F, inv_tab, mat, z):
    """Apply the projective matrix mat = (a, b, c, d) to z in P^1(F).

    z is either a field element or None (the point at infinity).
    """
    a, b, c, d = mat
    if z is None:
        # (a*inf + b)/(c*inf + d) = a / c
        if F.is_zero(c):
            return None
        return F.mul(a, inv_tab[c])
    num = F.add(F.mul(a, z), b)
    den = F.add(F.mul(c, z), d)
    if F.is_zero(den):
        return None
    return F.mul(num, inv_tab[den])


def find_primitive(F):
    """Smallest element of multiplicative order |F| - 1."""
    order = len(F.elements()) - 1
    fac = []
    m = order
    p = 2
    while p * p <= m:
        if m % p == 0:
            fac.append(p)
            while m % p == 0:
                m //= p
        p += 1
    if m > 1:
        fac.append(m)
    for x in F.elements():
        if F.is_zero(x):
            continue
        if all(not F.is_zero(F.sub(F.pow(x, order // r), F.pow(x, 0))) for r in fac):
            return x
    raise AssertionError("no primitive element found")


# ---------------------------------------------------------------------------
# BFS over the orbit of the base circle
# ---------------------------------------------------------------------------

def build_circles(q: int, check_orbit_size: bool = False):
    """Return (points, blocks) with blocks a list of tuples of point indices.

    points[i] is a field element of F_{q^2} for i < q^2 and None for i = q^2
    (the point at infinity).  blocks[0] is the base circle F_q u {infinity}.
    """
    F, sub = build_field(q)
    inv_tab = make_inverse_table(F)

    field_points = list(F.elements())
    zero = sub[0]
    one = F.pow(zero, 0)  # x^0 = 1 in any field
    points = field_points + [None]
    index = {x: i for i, x in enumerate(field_points)}
    infinity = len(points) - 1

    lam = find_primitive(F)
    gens = [
        (one, one, zero, one),        # z -> z + 1
        (lam, zero, zero, one),       # z -> lam * z
        (zero, one, one, zero),       # z -> 1 / z
    ]

    base = frozenset(list(sub)) | {None}

    seen = {base: 0}
    blocks = [base]
    frontier = [base]
    expected = q * (q * q + 1)

    while frontier:
        nxt = []
        for circ in frontier:
            for mat in gens:
                img = frozenset(apply_matrix(F, inv_tab, mat, z) for z in circ)
                if len(img) != q + 1:
                    continue  # degenerate image (should not happen)
                if img in seen:
                    continue
                seen[img] = len(blocks)
                blocks.append(img)
                nxt.append(img)
                if len(blocks) > 4 * expected:
                    raise AssertionError(
                        f"q={q}: orbit larger than 4q(q^2+1), generators are wrong")
        frontier = nxt

    if check_orbit_size and len(blocks) != expected:
        raise AssertionError(
            f"q={q}: orbit has {len(blocks)} circles, expected {expected}")

    idx_blocks = []
    for B in blocks:
        ids = sorted(infinity if z is None else index[z] for z in B)
        idx_blocks.append(tuple(ids))

    # make sure the base circle is blocks[0] in index form too
    base_ids = tuple(sorted([index[z] for z in sub] + [infinity]))
    assert idx_blocks[0] == base_ids, "base circle is not at index 0"
    return points, idx_blocks


def crosscheck(q: int) -> tuple[int, int]:
    """Compare the BFS circle set against the slow triple enumeration."""
    from inversive_all_q import build_inversive_plane

    points_slow, circles_slow = build_inversive_plane(q)
    idx_slow = {p: i for i, p in enumerate(points_slow)}
    slow = {frozenset(idx_slow[p] for p in c) for c in circles_slow}

    points, idx_blocks = build_circles(q, check_orbit_size=True)
    fast = {frozenset(b) for b in idx_blocks}
    return len(slow), len(fast), slow == fast


def write_circle_file(path: Path, idx_blocks, n: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        fh.write(f"{n} {len(idx_blocks)}\n")
        for B in idx_blocks:
            fh.write(f"{len(B)} " + " ".join(str(x) for x in B) + "\n")


def design_check(idx_blocks, n: int, q: int) -> dict:
    """Verify the 3-(q^2+1, q+1, 1) parameters."""
    from collections import Counter
    sizes = Counter(len(B) for B in idx_blocks)
    ok_params = (
        n == q * q + 1
        and len(idx_blocks) == q * (q * q + 1)
        and set(sizes) == {q + 1}
    )
    # every pair of points lies in q+1 circles; every triple in at most one
    pair = Counter()
    for B in idx_blocks:
        for i in range(len(B)):
            for j in range(i + 1, len(B)):
                pair[(B[i], B[j])] += 1
    pair_ok = set(pair.values()) == {q + 1} and len(pair) == n * (n - 1) // 2
    return {"n": n, "b": len(idx_blocks), "s": q + 1,
            "params_ok": ok_params, "pairs_ok": pair_ok,
            "pair_index": (min(pair.values()), max(pair.values())) if pair else None}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--q", type=int, nargs="+", required=True)
    ap.add_argument("--export", action="store_true",
                    help="write ../output/circles_q<q>.txt")
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--crosscheck", action="store_true")
    args = ap.parse_args()

    rows = []
    for q in args.q:
        if args.crosscheck and q <= 9:
            ns, nf, same = crosscheck(q)
            print(f"q={q}: slow={ns} fast={nf} identical={same}", flush=True)
            if not same:
                raise SystemExit(f"crosscheck FAILED at q={q}")
        points, idx_blocks = build_circles(q, check_orbit_size=True)
        info = design_check(idx_blocks, len(points), q)
        rows.append({"q": q, **info})
        print(f"q={q}: n={info['n']} b={info['b']} s={info['s']} "
              f"params_ok={info['params_ok']} pair_index={info['pair_index']}",
              flush=True)
        if args.export:
            path = (Path(__file__).resolve().parent.parent / "output"
                    / f"circles_q{q}.txt")
            write_circle_file(path, idx_blocks, len(points))
            print(f"  wrote {path} ({path.stat().st_size} bytes)", flush=True)

    if args.out:
        import json
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(rows, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
