"""Efficient inversive-plane construction for larger q.

The naive construction enumerates all ordered triples (t0,t1,t2) of P^1(F_{q^2}),
which is O((q^2+1)^3) Mobius evaluations -- far too slow for q >= 7.

Better: the circles are exactly the images of P^1(F_q) under PGL(2, F_{q^2}).
Instead of enumerating the group, we enumerate circles directly from the
defining property:

    A circle is the set of points of P^1(F_{q^2}) satisfying a "circle equation"
    with coefficients in F_{q^2} that is defined over F_q in the appropriate
    sense.

Concretely, in the model P^1(F_{q^2}) = F_{q^2} ∪ {∞}, the circles are exactly
the images of P^1(F_q) under PGL(2, F_{q^2}), and there are q(q^2+1) of them.
Each circle is determined by any 3 of its points.  So we can generate circles
by BFS: start from the base circle P^1(F_q), and close under the action of a
generating set of PGL(2, F_{q^2}).

A small generating set suffices: the maps
    z -> z + a   (a in F_{q^2})
    z -> b*z     (b in F_{q^2}^*)
    z -> 1/z
generate PGL(2, F_{q^2}) (it is generated by translations, dilations and
inversion).  Applying these to the base circle and closing under the orbit
gives all circles with O(#circles * #generators * q) work.

This script implements that BFS and verifies the design axioms.
"""

from __future__ import annotations

import argparse
import itertools
import json
from collections import Counter, deque
from pathlib import Path

from inversive_prime_power import FiniteField, factorize, find_irreducible


def build_field(q: int):
    fac = factorize(q)
    if len(fac) != 1:
        raise ValueError(f"q={q} is not a prime power")
    p, e = fac[0]
    F = FiniteField(p, 2 * e, find_irreducible(p, 2 * e))
    sub = [x for x in F.elements() if F.pow(x, q) == x]
    if len(sub) != q:
        raise AssertionError(f"subfield has {len(sub)} elements, expected {q}")
    return F, sub


def projective_line(F: FiniteField):
    out = set()
    for b in F.elements():
        if F.is_zero(b):
            continue
        for a in F.elements():
            out.add(F.div(a, b))
    return sorted(out) + [None]


def apply_map(F: FiniteField, z, kind: str, param):
    """Apply a generator of PGL(2) to z in P^1."""
    if kind == "translate":
        if z is None:
            return None
        return F.add(z, param)
    if kind == "dilate":
        if z is None:
            return None
        return F.mul(z, param)
    if kind == "invert":
        if z is None:
            return F.zero
        if F.is_zero(z):
            return None
        return F.inv(z)
    raise ValueError(kind)


def generators(F: FiniteField):
    """A generating set of PGL(2, F) acting on P^1.

    PGL(2,F) is generated by translations z -> z+a, dilations z -> b z, and
    inversion z -> 1/z.  But the *orbit* of the base circle under these maps
    only reaches circles whose "shape" is reachable by those specific maps;
    to get the full orbit we must also allow conjugation, i.e. we need the
    generators to generate the whole group, not just a subgroup.

    The subtlety: translations + dilations + inversion generate PGL(2,F) as an
    abstract group, but the BFS below applies a FIXED generating set repeatedly,
    which does generate the group.  The failure at q=3,5 (exactly half the
    circles) indicates the dilation generator was not a primitive element, so
    the multiplicative subgroup generated was too small.

    Fix: use a primitive element of F^* for the dilation.
    """
    gens = []
    # translations z -> z + a for a basis of F over F_p
    for i in range(F.e):
        a = tuple([0] * i + [1] + [0] * (F.e - i - 1))
        gens.append(("translate", a))
    # dilation by a primitive element of F^*
    prim = None
    for b in F.elements():
        if F.is_zero(b) or b == F.one:
            continue
        # primitive iff its multiplicative order is q-1
        if F.pow(b, F.q - 1) == F.one and all(
            F.pow(b, (F.q - 1) // r) != F.one for r in _prime_divisors(F.q - 1)
        ):
            prim = b
            break
    if prim is None:
        raise ValueError("no primitive element found")
    gens.append(("dilate", prim))
    # inversion
    gens.append(("invert", None))
    return gens


def _prime_divisors(n: int) -> list[int]:
    out = []
    d = 2
    while d * d <= n:
        if n % d == 0:
            out.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        out.append(n)
    return out


def circles_bfs(F: FiniteField, sub, points) -> set:
    """All circles, as the PGL(2)-orbit of the base circle P^1(F_q)."""
    base = frozenset(list(sub) + [None])
    gens = generators(F)
    seen = {base}
    queue = deque([base])
    while queue:
        cur = queue.popleft()
        for kind, param in gens:
            img = frozenset(apply_map(F, z, kind, param) for z in cur)
            if len(img) == len(base) and img not in seen:
                seen.add(img)
                queue.append(img)
    return seen


def verify_design(points, circles) -> dict:
    n = len(points)
    idx = {p: i for i, p in enumerate(points)}
    blocks = [frozenset(idx[p] for p in c) for c in circles]
    triple_count = Counter()
    for b in blocks:
        for tri in itertools.combinations(sorted(b), 3):
            triple_count[tri] += 1
    all_triples = set(itertools.combinations(range(n), 3))
    covered = set(triple_count)
    return {
        "points": n,
        "circles": len(blocks),
        "circle_sizes": dict(sorted(Counter(len(b) for b in blocks).items())),
        "triples_total": len(all_triples),
        "triples_covered": len(covered),
        "triples_missing": len(all_triples - covered),
        "max_triple_multiplicity": max(triple_count.values()) if triple_count else 0,
        "is_3_design": covered == all_triples and all(v == 1 for v in triple_count.values()),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--q", type=int, nargs="+", default=[3, 4, 5, 7, 8, 9])
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    rows = []
    for q in args.q:
        try:
            F, sub = build_field(q)
            points = projective_line(F)
            circles = circles_bfs(F, sub, points)
        except Exception as exc:  # noqa: BLE001
            print(f"q={q}: FAILED ({type(exc).__name__}: {exc})", flush=True)
            rows.append({"q": q, "error": f"{type(exc).__name__}: {exc}"})
            continue
        design = verify_design(points, circles)
        rows.append({"q": q, **design})
        print(f"q={q}: points={design['points']} (expect {q*q+1})  "
              f"circles={design['circles']} (expect {q*(q*q+1)})  "
              f"sizes={design['circle_sizes']}  3-design={design['is_3_design']}",
              flush=True)

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
