"""k=8: the full assembly, tested against the exhaustive counts.

The profile formula (verified at q=5,7) gives #4, #5, #6 circles per
(T, X) tuple.  The multiplicity theorem would say

    #8-sets with profile P = (tuples with P) / (#4-circles in P) * b

Let me test whether that holds for k=8 by assembling and comparing with
the exhaustive counts (0 at q=5 and q=7).

Run:  python arc_k8_assemble.py --q 5 7
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from collections import Counter
from fractions import Fraction
from math import comb
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from inversive_all_q import build_field, build_inversive_plane  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--q", type=int, nargs="+", default=[5, 7])
    args = ap.parse_args()

    rows = []
    for q in args.q:
        F, sub = build_field(q)
        points, circles = build_inversive_plane(q)
        idx = {p: i for i, p in enumerate(points)}
        blocks = [tuple(sorted(idx[p] for p in c)) for c in circles]
        n = len(points)
        b = len(blocks)
        s = q + 1
        base = set(sub) | {None}
        ci = None
        for k, B in enumerate(blocks):
            if set(points[i] for i in B) == base:
                ci = k
                break
        B = blocks[ci]
        Bset = set(B)
        outside = [p for p in range(n) if p not in Bset]

        prof_tuples = Counter()
        for T in itertools.combinations(B, 4):
            Tset = set(T)
            for X in itertools.combinations(outside, 4):
                Xset = set(X)
                v2 = v3 = v4 = u3 = u4 = z4 = 0
                for kk in range(b):
                    if kk == ci:
                        continue
                    ct = len(Tset & set(blocks[kk]))
                    cx = len(Xset & set(blocks[kk]))
                    if ct == 2:
                        if cx == 2:
                            v2 += 1
                        elif cx == 3:
                            v3 += 1
                        elif cx == 4:
                            v4 += 1
                    elif ct == 1:
                        if cx == 3:
                            u3 += 1
                        elif cx == 4:
                            u4 += 1
                    elif ct == 0:
                        if cx == 4:
                            z4 += 1
                n4 = 1 + v2 + u3 + z4
                n5 = v3 + u4
                n6 = v4
                prof_tuples[tuple([6] * n6 + [5] * n5 + [4] * n4)] += 1

        # assemble with the multiplicity theorem
        bad = Fraction(0)
        detail = {}
        nonint = []
        for prof, cnt in prof_tuples.items():
            n4 = sum(1 for t in prof if t == 4)
            sets = Fraction(cnt, n4) * b
            if sets.denominator != 1:
                nonint.append((str(prof), cnt, n4, str(sets)))
            bad += sets
            detail[str(prof)] = str(sets)

        # the (7,) and (8,) single-circle profiles are NOT generated by the
        # tuple loop (they have no 4-circle), so add them separately
        seven = b * comb(s, 7) * (n - s) if s >= 7 else 0
        eight = b * comb(s, 8) if s >= 8 else 0
        bad += seven + eight
        arcs = comb(n, 8) - bad

        row = {"q": q, "n": n, "b": b, "s": s,
               "num_profiles": len(prof_tuples),
               "profile_sets": detail,
               "seven": seven, "eight": eight,
               "bad": str(bad), "arcs": str(arcs),
               "C(n,8)": comb(n, 8),
               "bad_integer": bad.denominator == 1,
               "non_integer": nonint[:3],
               "consistent": bad + arcs == comb(n, 8)}
        rows.append(row)
        print(f"q={q}: n={n}, b={b}, s={s}, profiles {len(prof_tuples)}",
              flush=True)
        print(f"  (7,)={seven}  (8,)={eight}", flush=True)
        print(f"  bad = {bad}  (integer: {bad.denominator == 1})", flush=True)
        print(f"  arcs = {arcs}", flush=True)
        print(f"  C(n,8) = {comb(n,8)}", flush=True)
        print(f"  consistent: {row['consistent']}", flush=True)
        if nonint:
            print(f"  NON-INTEGER: {nonint[:2]}", flush=True)

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(rows, indent=2, ensure_ascii=False),
                            encoding="utf-8")
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
