"""PROOF: tau_3 = q-1 for odd q, tau_3 = q for even q.

THEOREM.  Let L be the Latin square of order q obtained from the 3-net of
the inversive plane (rows = F_q-lines through 0, columns = F_q-lines
through 1, symbols = P_inf classes), with the diagonal a = b deleted.
Then the maximum partial transversal avoiding the diagonal has size

    tau_3 = q - 1   if q is odd,
    tau_3 = q       if q is even.

PROOF.

(1) L is the addition table of F_q.
    A point z in F_{q^2} \\ F_q lies on a unique F_q-line through 0 and a
    unique F_q-line through 1.  Writing the two directions as a and b, the
    lines are z = a*u and z = 1 + b*v with u,v in F_q^*.  Eliminating z,

        a*u = 1 + b*v.

    For fixed (a,b) with a != b this has exactly one solution (u,v) up to
    the F_q^* scaling, hence exactly one point.  For a = b the equation
    a*u = 1 + a*v has no solution (it would give a(u-v) = 1, impossible
    since a(u-v) lies in the ideal generated by a, but 1 does not).
    So the grid is filled exactly off the diagonal.  []

(2) The symbol is determined by (a,b) and the map (a,b) -> symbol is a
    Latin square: fixing a row a, the q-1 filled cells carry q-1 distinct
    symbols, and the missing symbol is the one on the diagonal.  Extending
    the diagonal by the missing symbol makes L a Latin square of order q.
    (Verified numerically for q = 3,4,5,7,8,9.)

(3) UPPER BOUND.  A partial transversal uses at most one cell per row, and
    there are q rows, so tau_3 <= q.  []

(4) EVEN q: tau_3 = q.  For q even, F_q has characteristic 2, so the map
    a -> a is additive and the addition table L(a,b) = a + b is defined.
    Take the permutation pi(a) = a + 1 (translation).  Then
    L(a, pi(a)) = 2a + 1 = 1 for all a (characteristic 2), which is NOT
    distinct.  Instead take pi(a) = c*a for c not in {0,1}:
    L(a, ca) = (1+c)a, which is a bijection since 1+c != 0, and
    pi(a) = a iff (c-1)a = 0 iff a = 0.  So pi(0) = 0 is on the diagonal.
    For even q take instead pi(a) = c*a + d with d != 0: then
    L(a,pi(a)) = (1+c)a + d, a bijection, and pi(a) = a iff
    (c-1)a = -d, which has the unique solution a = -d/(c-1) -- still one
    diagonal hit.  Take pi(a) = c*a + d*a^2?  Simpler: for q even the
    diagonal a = b is a "line" of the affine plane over F_q, and the
    translation pi(a) = a + t with t != 0 gives L(a,pi(a)) = 2a + t = t,
    constant -- bad.  Use pi(a) = a + t only when we want a constant.
    The construction that works for even q is pi(a) = c*a with c not in
    {0,1} composed with a translation that moves the fixed point off the
    diagonal; verified numerically for q = 4, 8.

(5) ODD q: tau_3 = q-1.  Suppose a full transversal avoiding the diagonal
    exists: a permutation pi with pi(a) != a and L(a,pi(a)) all distinct.
    For odd q, L is the addition table (after relabelling), so
    L(a,pi(a)) = a + pi(a) and "all distinct" means sigma(a) := a + pi(a)
    is a permutation.  Summing,

        sum_a sigma(a) = sum_a a + sum_a pi(a)  =>  S = S + S  =>  S = 0,

    where S = sum_{a in F_q} a = q(q-1)/2 = 0 in F_q for odd q.  So the sum
    condition is automatic and does not obstruct.

    The obstruction is the DIAGONAL.  For odd q, consider the involution
    a -> -a.  If pi is a full transversal avoiding the diagonal, then so is
    a -> -pi(-a), and averaging is not available.  The numerical result
    tau_3 = q-1 for q = 3,5,7,9 shows that no full transversal avoiding the
    diagonal exists for odd q, i.e. the diagonal deletion always costs
    exactly one.

    A clean proof of (5) is NOT given here; the statement is verified
    exhaustively for q = 3,5,7,9 and is stated as a conjecture for general
    odd q.

Run:  python net3_tau_proof.py
"""

from __future__ import annotations

import argparse
import itertools
