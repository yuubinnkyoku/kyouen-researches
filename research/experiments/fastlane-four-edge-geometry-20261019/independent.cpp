// Independent curve-first enumeration, not the 4x4 determinant algorithm.
// Build: c++ -O2 -std=c++17 independent.cpp -o independent && ./independent
#include <algorithm>
#include <array>
#include <cassert>
#include <cstdint>
#include <iostream>
#include <set>
#include <vector>
using ll=long long;
using Point=std::pair<ll,ll>;
static const std::vector<Point> P={{12,8},{-8,0},{2,0},{-2,0},{3,5},{0,4},{0,-4},{24,-16},{12,-4},{24,-4},{12,-16}};
ll cross(Point a,Point b,Point c){return (b.first-a.first)*(c.second-a.second)-(b.second-a.second)*(c.first-a.first);}
std::set<int> curves(){
 std::set<int> edges;
 auto record=[&](int mask){if(__builtin_popcount((unsigned)mask)>=4){
  for(int i=0;i<11;i++)for(int j=i+1;j<11;j++)for(int k=j+1;k<11;k++)for(int l=k+1;l<11;l++){
   int e=(1<<i)|(1<<j)|(1<<k)|(1<<l);
   if((mask&e)==e)edges.insert(e);
  }
 }};
 // All lines are generated by pairs.
 for(int i=0;i<11;i++)for(int j=i+1;j<11;j++){
  int mask=0;for(int k=0;k<11;k++)if(cross(P[i],P[j],P[k])==0)mask|=1<<k;
  record(mask);
 }
 // All circles are generated by non-collinear triples. Integer-scaled equation
 // D(x*x+y*y)+A*x+B*y+C=0; no division or floating-point.
 for(int i=0;i<11;i++)for(int j=i+1;j<11;j++)for(int k=j+1;k<11;k++){
  if(cross(P[i],P[j],P[k])==0)continue;
  auto [xi,yi]=P[i];auto [xj,yj]=P[j];auto [xk,yk]=P[k];
  ll d=cross(P[i],P[j],P[k]);
  ll zi=xi*xi+yi*yi,zj=xj*xj+yj*yj,zk=xk*xk+yk*yk;
  ll A=-( (zj-zi)*(yk-yi)-(zk-zi)*(yj-yi) );
  ll B=-( (xj-xi)*(zk-zi)-(xk-xi)*(zj-zi) );
  ll C=-(d*zi+A*xi+B*yi);
  int mask=0;
  for(int t=0;t<11;t++){
   auto [x,y]=P[t];if(d*(x*x+y*y)+A*x+B*y+C==0)mask|=1<<t;
  }
  record(mask);
 }
 return edges;
}
int main(){
 auto E=curves();std::vector<int> expected={ (1<<0)|(1<<6)|(1<<9)|(1<<10), (1<<1)|(1<<2)|(1<<5)|(1<<6), (1<<3)|(1<<4)|(1<<5)|(1<<6), (1<<7)|(1<<8)|(1<<9)|(1<<10) };
 assert(E==std::set<int>(expected.begin(),expected.end()));
 constexpr int N=1<<11;
 std::array<unsigned char,N> safe{},g{};
 int count=0;
 for(int s=0;s<N;s++){
  bool ok=true;for(int e:E)if((s&e)==e){ok=false;break;}
  safe[s]=ok;count+=ok;
 }
 std::array<int,6> hist{};
 for(int s=N-1;s>=0;s--){
  if(!safe[s])continue;
  bool seen[12]={};
  for(int v=0;v<11;v++)if(!(s&(1<<v)) && safe[s|(1<<v)])seen[g[s|(1<<v)]]=true;
  int nim=0;while(seen[nim])nim++;
  assert(nim<6);g[s]=nim;hist[nim]++;
 }
 assert(count==1635 && g[0]==5);
 std::cout<<"edges="<<E.size()<<" safe="<<count<<" root="<<(int)g[0]<<" hist=";
 for(int x:hist)std::cout<<x<<",";
 std::cout<<" children=";
 for(int i=0;i<11;i++)std::cout<<(int)g[1<<i]<<",";
 std::cout<<"\n";
}
