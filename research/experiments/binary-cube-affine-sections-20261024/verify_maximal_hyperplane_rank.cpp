// Independent exhaustive affine-rank check of maximal hyperplane sections.
// For d=3,4, every q=2^(d-1) subset is tested, not only the listed flats.
// Over F_101 rank agrees with real rank: the integer 0/1 minors of order
// at most 5 have absolute value <= 5^(5/2) < 101 (Hadamard).
#include <algorithm>
#include <map>
#include <cassert>
#include <cstdint>
#include <iostream>
#include <set>
#include <vector>
using namespace std;
constexpr int MOD = 101;
int inverse(int a) {
    for (int b = 1; b < MOD; ++b) if (a*b%MOD==1) return b;
    assert(false); return 0;
}
int affine_rank(const vector<int>& points, int d) {
    int a[16][6]{};
    for (int i=0; i<(int)points.size(); ++i) {
        a[i][0]=1;
        for (int j=0;j<d;++j) a[i][j+1]=(points[i]>>j)&1;
    }
    int rank=0;
    for (int c=0;c<=d;++c) {
        int p=rank;
        while (p<(int)points.size() && !a[p][c]) ++p;
        if (p==(int)points.size()) continue;
        for (int j=c;j<=d;++j) swap(a[p][j],a[rank][j]);
        int factor=inverse(a[rank][c]);
        for (int j=c;j<=d;++j) a[rank][j]=a[rank][j]*factor%MOD;
        for (int i=rank+1;i<(int)points.size();++i) if (a[i][c]) {
            factor=a[i][c];
            for (int j=c;j<=d;++j)
                a[i][j]=(a[i][j]-factor*a[rank][j]%MOD+MOD)%MOD;
        }
        ++rank;
        if (rank==(int)points.size()) break;
    }
    return rank;
}
void check(int d) {
    int n=1<<d, q=1<<(d-1);
    set<uint64_t> expected, actual;
    for (int i=0;i<d;++i) for (int b=0;b<2;++b) {
        uint64_t mask=0;
        for (int x=0;x<n;++x) if (((x>>i)&1)==b) mask|=1ULL<<x;
        expected.insert(mask);
    }
    for (int i=0;i<d;++i) for (int j=i+1;j<d;++j)
        for (int b=0;b<2;++b) {
            uint64_t mask=0;
            for (int x=0;x<n;++x)
                if ((((x>>i)^(x>>j))&1)==b) mask|=1ULL<<x;
            expected.insert(mask);
        }
    vector<int> chosen;
    long long subsets=0;
    auto dfs=[&](auto&& self,int first)->void {
        if ((int)chosen.size()==q) {
            ++subsets;
            if (affine_rank(chosen,d)<=d) {
                uint64_t mask=0;
                for (int x:chosen) mask|=1ULL<<x;
                actual.insert(mask);
            }
            return;
        }
        for (int x=first;x<=n-(q-(int)chosen.size());++x) {
            chosen.push_back(x);self(self,x+1);chosen.pop_back();
        }
    };
    dfs(dfs,0);
    assert(actual==expected);
    assert((int)actual.size()==d*(d+1));
    cout<<"d="<<d<<" q="<<q<<" subsets="<<subsets
        <<" coplanar="<<actual.size()<<" PASS\n";
}
void audit_strong(int d);
void audit_minimal(int d);
int main() { check(3); check(4); for (int d = 1; d <= 5; ++d) audit_minimal(d); audit_strong(3); audit_strong(4); }


// Independent strong-game audit: forbidden q-sets are generated by affine rank,
// not by the coordinate/diagonal hyperplane description used by Python.
void audit_strong(int d) {
    int n = 1 << d, q = n / 2, N = 1 << n;
    vector<uint64_t> forbidden;
    for (int mask = 0; mask < N; ++mask) {
        if (__builtin_popcount((unsigned)mask) != q) continue;
        vector<int> points;
        for (int i = 0; i < n; ++i)
            if ((mask >> i) & 1) points.push_back(i);
        if (affine_rank(points, d) <= d)
            forbidden.push_back((uint64_t)mask);
    }
    assert((int)forbidden.size() == d * (d + 1));

    vector<uint8_t> safe(N, 1), g(N), h(N);
    for (int mask = 0; mask < N; ++mask)
        for (uint64_t f : forbidden)
            if (((uint64_t)mask & f) == f) {
                safe[mask] = 0;
                break;
            }

    map<int, int> terminal;
    map<pair<int, int>, int> pairs;
    int swap_fail = 0, safe_count = 0;
    for (int mask = N - 1; mask >= 0; --mask) {
        if (!safe[mask]) continue;
        ++safe_count;
        unsigned mex_bits = 0;
        unsigned free = ((unsigned)N - 1) ^ (unsigned)mask;
        while (free) {
            unsigned bit = free & -free;
            free -= bit;
            int child = mask | (int)bit;
            if (!safe[child]) continue;
            mex_bits |= 1u << g[child];
            mex_bits |= 1u << (h[child] + 8);
        }
        if (!mex_bits) {
            h[mask] = 1;
            ++terminal[__builtin_popcount((unsigned)mask)];
        } else {
            while (mex_bits & (1u << g[mask])) ++g[mask];
            while (mex_bits & (1u << (h[mask] + 8))) ++h[mask];
        }
        ++pairs[{g[mask], h[mask]}];
        swap_fail += (g[mask] <= 1
            ? h[mask] != 1 - g[mask] : h[mask] != g[mask]);
    }
    if (d == 3) {
        assert(safe_count == 159);
        assert((terminal == map<int, int>{{4, 24}, {5, 8}}));
        assert(g[0] == 0 && h[0] == 0 && swap_fail == 25);
        assert((pairs == map<pair<int, int>, int>{
            {{0, 0}, 17}, {{0, 1}, 40}, {{1, 0}, 46},
            {{2, 1}, 8}, {{2, 2}, 48}}));
    } else {
        assert(d == 4 && safe_count == 61719);
        assert((terminal == map<int, int>{{11, 192}, {12, 560}}));
        assert(g[0] == 0 && h[0] == 1 && swap_fail == 0);
        assert((pairs == map<pair<int, int>, int>{
            {{0, 1}, 29367}, {{1, 0}, 30720}, {{2, 2}, 1632}}));
    }
    cout << "strong d=" << d << " safe=" << safe_count
         << " terminal=";
    for (auto [k, v] : terminal) cout << k << ":" << v << " ";
    cout << "root=" << (int)g[0] << "," << (int)h[0]
         << " swap_fail=" << swap_fail << " PASS\n";
}

// Different minimality test from Python: delete each point and explicitly
// search for an uncovered hyperplane. Exhaust t<=d+2, d<=5.
void audit_minimal(int d) {
    int n = 1 << d;
    vector<uint64_t> family;
    for (int i = 0; i < d; ++i)
        for (int b = 0; b < 2; ++b) {
            uint64_t f = 0;
            for (int x = 0; x < n; ++x)
                if (((x >> i) & 1) == b) f |= 1ULL << x;
            family.push_back(f);
        }
    for (int i = 0; i < d; ++i)
        for (int j = i + 1; j < d; ++j)
            for (int b = 0; b < 2; ++b) {
                uint64_t f = 0;
                for (int x = 0; x < n; ++x)
                    if ((((x >> i) ^ (x >> j)) & 1) == b)
                        f |= 1ULL << x;
                family.push_back(f);
            }
    vector<uint64_t> counts(d + 3, 0);
    set<uint64_t> extremal;
    vector<int> chosen;
    auto dfs = [&](auto&& self, int next, int left, uint64_t mask) -> void {
        if (!left) {
            for (uint64_t f : family)
                if (!(mask & f)) return;
            for (int x : chosen) {
                uint64_t smaller = mask ^ (1ULL << x);
                bool necessary = false;
                for (uint64_t f : family)
                    if (!(smaller & f)) { necessary = true; break; }
                if (!necessary) return;
            }
            ++counts[chosen.size()];
            if ((int)chosen.size() == d + 1) extremal.insert(mask);
            return;
        }
        for (int x = next; x <= n - left; ++x) {
            chosen.push_back(x);
            self(self, x + 1, left - 1, mask | (1ULL << x));
            chosen.pop_back();
        }
    };
    for (int t = 2; t <= d + 2; ++t) dfs(dfs, 0, t, 0);

    uint64_t expected = 1ULL << (d - 1);
    for (int j = 1; j <= d; ++j) expected *= (uint64_t)j;
    assert(counts[d + 1] == expected && counts[d + 2] == 0);
    const vector<vector<uint64_t>> known = {
        {}, {0, 0, 1, 0},
        {0, 0, 0, 4, 0},
        {0, 0, 0, 8, 24, 0},
        {0, 0, 0, 0, 560, 192, 0},
        {0, 0, 0, 0, 3360, 26496, 1920, 0}
    };
    assert(counts == known[d]);
    // Independently construct all geodesics and compare as sets.
    set<uint64_t> geodesics;
    vector<int> order(d);
    for (int i = 0; i < d; ++i) order[i] = i;
    for (int start = 0; start < n; ++start) {
        do {
            int x = start;
            uint64_t path = 1ULL << x;
            for (int axis : order) {
                x ^= 1 << axis;
                path |= 1ULL << x;
            }
            geodesics.insert(path);
        } while (next_permutation(order.begin(), order.end()));
    }
    assert(geodesics == extremal);
    cout << "minimal d=" << d << " extremal=" << expected << " spectrum=";
    for (int t = 2; t <= d + 2; ++t)
        if (counts[t]) cout << t << ":" << counts[t] << " ";
    cout << "PASS\n";
}
