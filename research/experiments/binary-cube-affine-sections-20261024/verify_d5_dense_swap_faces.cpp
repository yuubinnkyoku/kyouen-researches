// Exhaustive d=5, q=16 high-density hyperplane game near-terminal census.
// Independent face-mask implementation; vertices are 5-bit integers.
// g: normal mex, h: misere mex with terminal value 1.
// g++ -std=c++17 -O3 -Wall -Wextra -Werror verify_d5_dense_swap_faces.cpp -o /tmp/d5faces && /tmp/d5faces
#include <algorithm>
#include <array>
#include <cassert>
#include <cstdint>
#include <iostream>
#include <unordered_map>
#include <vector>
using namespace std;
using U=uint32_t;
static vector<U> faces;
static bool safe(U m){for(U f:faces)if(!(m&f))return false;return true;}
static int mex(int x){int r=0;while(x&(1<<r))r++;return r;}
template<class F> static void each_comb(int n,int k,F &&func){
    uint64_t m=(uint64_t(1)<<k)-1,lim=uint64_t(1)<<n;
    while(m<lim){func(U(m));uint64_t a=m&-m,b=m+a;m=(((m^b)>>2)/a)|b;}
}
int main(){
    for(int i=0;i<5;i++)for(int v=0;v<2;v++){
        U f=0;for(int x=0;x<32;x++)if(((x>>i)&1)==v)f|=U(1)<<x;
        faces.push_back(f);
    }
    for(int i=0;i<5;i++)for(int j=0;j<i;j++)for(int v=0;v<2;v++){
        U f=0;for(int x=0;x<32;x++)if((((x>>i)^(x>>j))&1)==v)f|=U(1)<<x;
        faces.push_back(f);
    }
    assert(faces.size()==30);
    unordered_map<U,int> prev,curr;
    size_t counts[8]={},bad7=0,pairs7[8][8]={};
    vector<U> bad_masks;
    for(int t=4;t<=7;t++){
        curr.clear();
        if(t<7)curr.reserve(t==4?4000:(t==5?130000:900000));
        each_comb(32,t,[&](U m){
            if(!safe(m))return;
            counts[t]++;
            int gbits=0,hbits=0;bool move=false;
            for(U z=m;z;z&=z-1){
                U c=m^(z&-z);
                auto it=prev.find(c);
                if(it==prev.end())continue;
                move=true;int v=it->second;
                gbits|=1<<(v/8);hbits|=1<<(v%8);
            }
            int g=move?mex(gbits):0,h=move?mex(hbits):1;
            if(t<7)curr.emplace(m,8*g+h);
            else {
                assert(g<8&&h<8);
                pairs7[g][h]++;
                if(h!=(g<2?1-g:g)){
                    assert(g==0&&h==0);
                    bad7++;bad_masks.push_back(m);
                }
            }
        });
        cout<<"t="<<t<<" safe="<<counts[t]<<'\n';
        prev.swap(curr);
    }
    assert(counts[4]==3360&&counts[5]==89376&&counts[6]==675472&&counts[7]==3025376);
    assert(bad7==34560);
    cout<<"t=7 pairs:";
    for(int g=0;g<8;g++)for(int h=0;h<8;h++)if(pairs7[g][h])
        cout<<" ("<<g<<","<<h<<"):"<<pairs7[g][h];
    cout<<"\nviolations="<<bad7<<'\n';
    // Automorphisms generated by 5 coordinate flips and 4 adjacent swaps.
    array<array<int,32>,9> generators{};
    for(int j=0;j<5;j++)for(int x=0;x<32;x++)generators[j][x]=x^(1<<j);
    for(int j=0;j<4;j++)for(int x=0;x<32;x++){
        int a=(x>>j)&1,b=(x>>(j+1))&1;
        generators[5+j][x]=(x&~((1<<j)|(1<<(j+1))))|(a<<(j+1))|(b<<j);
    }
    unordered_map<U,bool> remaining;remaining.reserve(bad_masks.size()*2);
    for(U m:bad_masks)remaining.emplace(m,true);
    vector<pair<int,U>> orbits;
    for(U start:bad_masks){
        if(!remaining.at(start))continue;
        vector<U> queue{start};remaining[start]=false;
        for(size_t pos=0;pos<queue.size();pos++){
            U m=queue[pos];
            for(const auto &gen:generators){
                U image=0;
                for(U z=m;z;z&=z-1)image|=U(1)<<gen[__builtin_ctz(z)];
                auto it=remaining.find(image);
                assert(it!=remaining.end());
                if(it->second){it->second=false;queue.push_back(image);}
            }
        }
        orbits.push_back({int(queue.size()),start});
    }
    sort(orbits.begin(),orbits.end());
    assert(orbits.size()==13);
    int n1920=0,n3840=0;
    for(auto [sz,rep]:orbits){
        if(sz==1920)n1920++;else if(sz==3840)n3840++;else assert(false);
        cout<<"orbit size "<<sz<<" T={";
        bool first=true;
        for(U z=rep;z;z&=z-1){
            if(!first)cout<<",";
            first=false;cout<<__builtin_ctz(z);
        }
        cout<<"}\n";
    }
    assert(n1920==8&&n3840==5);
}
