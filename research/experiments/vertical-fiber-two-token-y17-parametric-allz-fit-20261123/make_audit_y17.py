    # independent recomputation of the declared probe box (z=0..30, x=17..z+33,
    # R<=x+z+36); no input from probe_rows.txt
    rows = pts = 0
    for z in range(0, 31):
        for x in range(17, z + 34):
            rows += 1
            pts += x + z + 36
    return rows, pts

