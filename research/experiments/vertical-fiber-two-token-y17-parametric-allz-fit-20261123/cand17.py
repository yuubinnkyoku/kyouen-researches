import sys

Y = 17

def q_odd(k):
    return k if k % 2 == 1 else k - 1

def single_token_val(S, R):
    # K0832 published single-token closed form, z-independent rows (merge region)
    if R == 0:
        return 0
    if R % 2 == 1 and R <= q_odd(S):
        return 2
    if S % 2 == 1 and R >= q_odd(S) + 1:
        return 1
    return 0

def in_T17(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        S = x + Y
        return R % 2 == 1 and R <= q_odd(S)
    d = x - z
    o = R - z
    if d == -Y:
        cap = (z + Y - 1) if z % 2 == 1 else (z + Y)
        if R % 2 == 1 and R <= (z if z % 2 == 1 else z - 1):
            return True
        if z % 2 == 1:
            return o % 2 == 0 and 2 <= o <= cap - z
        else:
            return o % 2 == 1 and 1 <= o <= cap - z
    if z % 2 == 1:
        ladder = R % 2 == 1 and R <= z
        if (d + 3 * Y) % 4 == 0:
            o_pin = (d + 3 * Y) // 2
            if Y + 1 <= o_pin <= 2 * Y and R == z + o_pin:
                return True
        if d == Y + 1:
            return ladder or (o % 2 == 0 and 2 * Y <= o <= x + Y)
        if d >= Y + 2:
            return ladder or R == z + 2 * Y
        return ladder
    else:
        ladder = R % 2 == 1 and R <= z - 1
        if (d + 3 * Y) % 4 == 2:
            o_pin = (d + 3 * Y) // 2
            if Y + 1 <= o_pin <= 2 * Y and R == z + o_pin:
                return True
        if d == Y + 1:
            return ladder or (o % 2 == 1 and 2 * Y + 1 <= o <= x + Y)
        if d >= Y + 2:
            return ladder or R == z + 2 * Y + 1
        return ladder

def _bk(off, k):
    return 1 <= off <= 2 * k - 1 and off % 2 == 1

def in_P17(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        S = x + Y
        return S % 2 == 1 and R >= q_odd(S) + 1
    d = x - z
    off = R - z
    b17 = _bk(off, Y)
    band_base = off % 2 == 0 and 2 * Y + 2 <= off <= x + Y          # steady base rows
    band_int = off % 2 == 0 and 2 * Y + 2 <= off <= x + Y - 1       # steady I rows
    tail = x % 2 == 0 and R >= x + z + Y + 1                         # S odd rows (y=17: x even)
    if z % 2 == 1:
        if -Y <= d <= Y and d % 2 == 1:
            k = (d + 3 * Y + 1) // 4      # I rows: b_k U I[2k+1)  (diag d=-17 included, k=8)
            return _bk(off, k) or off >= 2 * k + 1
        if d == Y + 1:
            return b17                     # sweep row, base type: z odd x odd
        if d >= Y + 2:
            if d % 2 == 0:
                return b17 or band_base
            return b17 or band_int or tail
        return _bk(off, (d + 3 * Y + 1) // 4)  # base rows d even in [-16,16]
    else:
        if d == -Y:
            return False                   # even-z diagonal: no value-1 at all (10th consecutive candidate)
        if d == Y + 1:
            return b17 or band_int or tail     # sweep row, I type: z even x even
        if d >= Y + 2:
            if d % 2 == 1:
                return b17 or band_base
            return b17 or band_int or tail
        if d % 2 == 0:
            k = (d + 3 * Y - 1) // 4       # I rows: b_k U I[2k+1)
            return _bk(off, k) or off >= 2 * k + 1
        return _bk(off, (d + 3 * Y + 1) // 4)  # base rows d odd in [-15,17]

def cand17(z, x, R):
    if R <= 0:
        return 0
    if in_T17(z, x, R):
        return 2
    if in_P17(z, x, R):
        return 1
    return 0

def main():
    if len(sys.argv) == 1 or (len(sys.argv) > 1 and sys.argv[1] == 'selfcheck'):
        n = mm = ov = 0
        hist = {}
        bad_ex = []
        for line in open('probe_rows.txt'):
            head, body = line.split('::')
            meta = dict(p.split('=') for p in head.split())
            z, x = int(meta['z']), int(meta['x'])
            assert x >= 17, ("below family domain", z, x)
            vals = []
            for seg in body.split():
                v, c = seg.split('x')
                vals.extend([int(v)] * int(c))
            for i, v in enumerate(vals):
                R = i + 1
                n += 1
                hist[v] = hist.get(v, 0) + 1
                c = cand17(z, x, R)
                if c != v:
                    mm += 1
                    if len(bad_ex) < 40:
                        bad_ex.append((z, x, R, v, c))
                if in_T17(z, x, R) and in_P17(z, x, R):
                    ov += 1
        print("probe points:", n, "mismatch:", mm, "overlap:", ov)
        print("value histogram:", {k: hist.get(k, 0) for k in sorted(hist)})
        for t in bad_ex:
            print("BAD", t)
        return
    print(__doc__)

if __name__ == '__main__':
    main()
