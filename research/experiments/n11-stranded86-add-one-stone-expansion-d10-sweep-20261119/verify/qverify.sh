#!/bin/bash
declare -A DIRS=(
 [00000000000000801202000001040200]=out80120204
 [00000000000000821082040200000000]=out82108204
 [00000000000000821092200000000000]=out82109220
 [00000000001020003800000048000000]=out10200038
)
ORDER=(00000000000000801202000001040200 00000000000000821082040200000000 00000000000000821092200000000000 00000000001020003800000048000000)
i=$1; step=2
while [ $i -lt ${#ORDER[@]} ]; do
  H=${ORDER[$i]}; D=${DIRS[$H]}
  echo "$(date +%T) worker$i START $H"
  ./verify_one.sh "$H" "$D" && echo "$(date +%T) worker$i DONE $H" || echo "$(date +%T) worker$i FAIL $H"
  i=$((i+step))
done
