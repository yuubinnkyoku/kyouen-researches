# group_catalog_verify.py - independent verification of the maximal collinear /
# concyclic group catalog of the 7x7 kyouen board (size >= 4 grid points).
#   * Recomputes ALL lines (via pairwise directions) and ALL circles meeting
#     the grid in >= 3 points (via exact-rational circumcircles over all
#     C(49,3) triples) - no reuse of the quartet enumeration machinery.
#   * Verifies: (a) census of group sizes, (b) the published decomposition
#     sums sum C(len,4) = 660 (lines) + 5704 (circles) = 6364 = F_7,
#     (c) every forbidden quartet in the provided catalog lies in exactly
#     one maximal group of its own type (partition property),
#     (d) no circle carries exactly 7 grid points and none carries more
#     than 8 (7x7-specific facts established by full enumeration),
#     (e) the recomputed group set equals, item for item, the catalog file
#     produced by scripts/max14_structure.mjs when given as argv[3].
# Usage: python3 group_catalog_verify.py <quartets_n7.txt> <out.jsonl> [group_catalog_n7.json]
# Determinism: no randomness, no timing; single JSON output line.
import json
import math
import sys
from collections import Counter
from fractions import Fraction
from itertools import combinations

qpath, outpath = sys.argv[1], sys.argv[2]
catalog_path = sys.argv[3] if len(sys.argv) > 3 else None

R = range(7)
pts = [(x, y) for x in R for y in R]
cell = lambda p: p[0] * 7 + p[1]

# ---- lines (maximal by construction from direction classes) ----
line_classes = {}
for a, b in combinations(pts, 2):
    dx, dy = b[0] - a[0], b[1] - a[1]
    g = math.gcd(abs(dx), abs(dy))
    dx, dy = dx // g, dy // g
    if dx < 0 or (dx == 0 and dy < 0):
        dx, dy = -dx, -dy
    const = a[1] * dx - a[0] * dy
    line_classes.setdefault((dx, dy, const), set()).update((a, b))
all_lines = [tuple(sorted(cell(p) for p in s)) for s in line_classes.values()]
lines_ge4 = sorted([l for l in all_lines if len(l) >= 4])
line_census_all = dict(sorted(Counter(len(l) for l in all_lines).items()))
line_census_ge4 = dict(sorted(Counter(len(l) for l in lines_ge4).items()))

# ---- circles (exact rational circumcenters over all triples) ----
def circumcenter(a, b, c):
    ax, ay = a; bx, by = b; cx, cy = c
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    if d == 0:
        return None, None
    ux = Fraction((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay)
                  + (cx * cx + cy * cy) * (ay - by), d)
    uy = Fraction((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx)
                  + (cx * cx + cy * cy) * (bx - ax), d)
    return ux, uy

seen = set()
for a, b, c in combinations(pts, 3):
    ux, uy = circumcenter(a, b, c)
    if ux is None:
        continue
    r2 = (a[0] - ux) ** 2 + (a[1] - uy) ** 2
    seen.add((ux, uy, r2))
circle_sizes, circ_groups = Counter(), set()
for (ux, uy, r2) in seen:
    cells = tuple(sorted(cell(p) for p in pts
                         if (p[0] - ux) ** 2 + (p[1] - uy) ** 2 == r2))
    circle_sizes[len(cells)] += 1
    if len(cells) >= 4:
        circ_groups.add(cells)
circle_census_ge3 = dict(sorted(circle_sizes.items()))
circles_ge4 = sorted(circ_groups)
circle_census_ge4 = dict(sorted(Counter(len(c) for c in circles_ge4).items()))

# ---- forbidden quartets ----
qt = [l for l in open(qpath).read().split('\n') if l and not l.startswith('n=')]
quads = [tuple(sorted(int(v) for v in l.split())) for l in qt]
assert len(quads) == 6364, len(quads)
assert len(set(quads)) == 6364

# ---- partition property ----
def collinear4(q):
    pts4 = [(c // 7, c % 7) for c in q]
    (x0, y0), (x1, y1) = pts4[0], pts4[1]
    return all((x1 - x0) * (y - y0) - (y1 - y0) * (x - x0) == 0 for (x, y) in pts4[2:])

key2group = {}
for g in lines_ge4:
    for four in combinations(g, 4):
        assert four not in key2group
        key2group[four] = ('L', g)
for g in circles_ge4:
    for four in combinations(g, 4):
        assert four not in key2group
        key2group[four] = ('C', g)
sum_lines = sum(math.comb(len(g), 4) for g in lines_ge4)
sum_circles = sum(math.comb(len(g), 4) for g in circles_ge4)
assert len(key2group) == sum_lines + sum_circles

ok_types, mismatches = 0, 0
for q in quads:
    kind = key2group.get(q)
    if kind is None:
        mismatches += 1
        continue
    typ, g = kind
    is_line = collinear4(q)
    if (typ == 'L') != is_line:
        mismatches += 1
    else:
        ok_types += 1

# 4-subsets generated by groups that are NOT in the forbidden catalog (should be none,
# because every 4-subset of a maximal collinear/concyclic group is itself a group 4-subset
# and must be forbidden)
generated = set(key2group.keys())
assert generated == set(quads), (len(generated), len(set(quads)))

# ---- checks ----
checks = {
    'line_census_all': line_census_all,
    'line_census_ge4': line_census_ge4,
    'circles_total_meeting_grid_ge3': sum(circle_sizes.values()),
    'circle_census_ge3': circle_census_ge3,
    'circle_census_ge4': circle_census_ge4,
    'sum_c4_lines': sum_lines,
    'sum_c4_circles': sum_circles,
    'sum_c4_total': sum_lines + sum_circles,
    'equals_published_F7_6364': sum_lines + sum_circles == 6364,
    'equals_published_collinear_660': sum_lines == 660,
    'equals_published_circular_5704': sum_circles == 5704,
    'quartet_partition_ok': mismatches == 0 and ok_types == 6364,
    'quartet_partition_type_mismatches': mismatches,
    'no_circle_with_exactly_7_grid_points': circle_sizes.get(7, 0) == 0,
    'max_circle_grid_points': max(circle_sizes),
    'eight_point_circles': circle_sizes.get(8, 0),
}
if catalog_path:
    cat = json.load(open(catalog_path))
    cat_lines = sorted(tuple(g) for g in cat['lines'])
    cat_circles = sorted(tuple(g) for g in cat['circles'])
    checks['catalog_file_lines_match'] = cat_lines == lines_ge4
    checks['catalog_file_circles_match'] = cat_circles == circles_ge4
    checks['catalog_file_sum_checks'] = cat['verified_sums']['lines_sum_C_len4'] == 660 \
        and cat['verified_sums']['circles_sum_C_len4'] == 5704

out = {'verifier': 'group_catalog_verify.py', 'n': 7, 'N': 49, 'checks': checks,
       'all_ok': all(v for k, v in checks.items() if isinstance(v, bool))}
open(outpath, 'w').write(json.dumps(out, sort_keys=True) + '\n')
print(json.dumps(out, sort_keys=True))
