# transcription of the T_21(x) / P_21(x) boxes from K0914 report.md) ----
def k0914_is_2(x, R):
    if R in (1, 3, 5):
        return True
    if x == 21 and R == 45:
        return True
    if x == 25 and R == 47:
        return True
    if x == 28 and R in (49, 51, 53, 55):
        return True
    if x >= 29 and R == 49:
        return True
    return False


def k0914_is_1(x, R):
    # the R >= 7 gate common to every published P_21(x) box
    if not (7 <= R):
        return False
    # explicit mirror of the published P_21(x) box table (report.md verbatim):
    if x == 21:
        return R % 2 == 1 and 7 <= R <= 43
    if x == 22:
        # O[7,inf) ∪ E[46,inf)
        return (R % 2 == 1) or (R % 2 == 0 and R >= 46)
    if x == 23:
        return R % 2 == 1 and 7 <= R <= 45
    if x == 24:
        return (R % 2 == 1) or (R % 2 == 0 and R >= 48)
    if x == 25:
        return R % 2 == 1 and 7 <= R <= 45
    if x == 26:
        return (R % 2 == 1) or (R % 2 == 0 and R >= 48)
    if x == 27:
        return R % 2 == 1 and 7 <= R <= 47
    if x == 28:
        if R % 2 == 1:
            return 7 <= R <= 47 or R >= 57
        return R >= 50
    if x == 29:
        if R % 2 == 1:
            return 7 <= R <= 47
        return 50 <= R <= 56
    if x >= 30 and x % 2 == 1:
        if R % 2 == 1:
            return 7 <= R <= 47
        return 50 <= R <= x + 27
    if x >= 30 and x % 2 == 0:
        if R % 2 == 1:
            return 7 <= R <= 47 or R >= x + 29
        return R >= 50
    raise AssertionError("unreachable x=%d" % x)


def k0914_val(x, R):
    if k0914_is_2(x, R):
        return 2
    if k0914_is_1(x, R):
        return 1
    return 0


