#!/usr/bin/env python3
"""Closed-form candidate cand10 for the y=10 two-token family H(R;(x,10);z).

Fitted from raw double-recursion probe rows (probe_rows.txt, z=0..30,
x=10..z+27, R<=x+z+26, 72,261 points, canonical descending-multiset engine)
plus the published y=10 raw skeleton survey
(research/log/2026-11-20-y10-two-token-skeleton-raw-survey.md).

Value classes relative to column height z, with offset o = R - z and d = x - z:
  b_k (base sets)  = odd offsets {1, 3, ..., 2k-1}  (value 1)
  base10 = b_10 = odd offsets {1, ..., 19}
  Ladder (value 2): odd R in [1, z]  (z odd) / [1, z-1] (z even)  -- offset parity: even (z odd) / odd (z even), o <= 0
  Diagonal row d=-10: T = O[1, z+10] (z odd) / O[1, z+9] (z even); P empty (z even) / b6 U I[12,inf) (z odd)
  Pin rows (value-2 single offsets):
     z odd : d in {-6,-2,2,6,10}  -> pin offset (d+30)/2 in {12,14,16,18,20}
     z even: d in {-8,-4,0,4,8}   -> pin offset (d+30)/2 in {11,13,15,17,19}
  Sweep row d=11:
     z odd : T band = even offsets [20, x+10]; P = base10 only
     z even: T band = odd offsets  [21, x+10]
  Steady rows d>=12: T pin offset 20 (z odd) / 21 (z even)
  Value-1 mid band both parities: even offsets [22, x+10] for d>=11 rows (sweep/steady),
  which for tail-compatible rows (x odd) continues into the infinite tail I[x+11, inf).
  Infinite interval rows (tail-compatible x odd) near the diagonal instead emit
     I[th(d), inf) with th(d) per the zigzag table below.

This is a FINITE FIT on the probe box plus out-of-box spot checks; no universal claim.
Running this file (with or without the 'selfcheck' argument) re-verifies cand10
against probe_rows.txt (all points, RLE rows regenerated by probe_y10.py) and
prints the mismatch/overlap counts; expected output is
"probe points: 72261 mismatch: 0 overlap: 0".
"""
import sys

Y = 10

def q_odd(k):
    return k if k % 2 == 1 else k - 1

def single_token_val(S, R):
    # K0832 published single-token closed form, z-independent rows (merge region)
    if R == 0:
        return 0
    if R % 2 == 1 and R <= q_odd(S):
        return 2
    if S % 2 == 1 and R >= q_odd(S) + 1:
        return 1
    return 0

def in_T10(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        return R % 2 == 1 and R <= q_odd(x + Y)
    d = x - z
    if d == -Y:
        return R % 2 == 1 and R <= (z + Y if z % 2 == 1 else z + Y - 1)
    if z % 2 == 1:
        if d in (-7, -3, 1, 5, 9):
            # not a y=10 pin class; plain ladder (keep template explicit)
            return R % 2 == 1 and R <= z
        if d in (-6, -2, 2, 6, 10):
            pin = z + (d + 3 * Y) // 2
            return (R % 2 == 1 and R <= z) or R == pin
        if d == Y + 1:
            return (R % 2 == 1 and R <= z) or ((R - z) % 2 == 0 and z + 2 * Y <= R <= x + z + Y)
        if d >= Y + 2:
            return (R % 2 == 1 and R <= z) or R == z + 2 * Y
        return R % 2 == 1 and R <= z
    else:
        if d in (-9, -7, -5, -3, -1, 1, 3, 5, 7, 9):
            return R % 2 == 1 and R <= z - 1
        if d in (-8, -4, 0, 4, 8):
            pin = z + (d + 3 * Y) // 2
            return (R % 2 == 1 and R <= z - 1) or R == pin
        if d == -Y:  # handled above
            return R % 2 == 1 and R <= z + Y - 1
        if d == 10:
            return R % 2 == 1 and R <= z - 1
        if d == Y + 1:
            return (R % 2 == 1 and R <= z - 1) or (R % 2 == 1 and z + 2 * Y + 1 <= R <= x + z + Y)
        if d >= Y + 2:
            return (R % 2 == 1 and R <= z - 1) or R == z + 2 * Y + 1
        return R % 2 == 1 and R <= z - 1

def _bk(off, k):
    return 1 <= off <= 2 * k - 1 and off % 2 == 1

def in_P10(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        S = x + Y
        return S % 2 == 1 and R >= q_odd(S) + 1
    d = x - z
    off = R - z
    base10 = _bk(off, 10)
    band = (2 * Y + 2 <= off <= x + Y) and off % 2 == 0
    tail = x % 2 == 1 and R >= x + z + Y + 1
    if z % 2 == 1:
        # interval rows: d even; base th(d) zigzag
        if d == -10: return _bk(off, 6) or R >= z + 12
        if d == -9: return _bk(off, 5)
        if d == -8: return _bk(off, 6) or R >= z + 12
        if d == -7: return _bk(off, 6)
        if d == -6: return _bk(off, 7) or R >= z + 14
        if d == -5: return _bk(off, 6)
        if d == -4: return _bk(off, 7) or R >= z + 14
        if d == -3: return _bk(off, 7)
        if d == -2: return _bk(off, 8) or R >= z + 16
        if d == -1: return _bk(off, 7)
        if d == 0: return _bk(off, 8) or R >= z + 16
        if d == 1: return _bk(off, 8)
        if d == 2: return _bk(off, 9) or R >= z + 18
        if d == 3: return _bk(off, 8)
        if d == 4: return _bk(off, 9) or R >= z + 18
        if d == 5: return _bk(off, 9)
        if d == 6: return _bk(off, 10) or R >= z + 20
        if d == 7: return _bk(off, 9)
        if d == 8: return _bk(off, 10) or R >= z + 20
        if d == 9: return _bk(off, 10)
        if d == 10: return _bk(off, 10) or R >= z + 21  # pin offset 20 is value 2
        if d == 11: return base10  # sweep row: no value-1 beyond base
        return base10 or band or tail
    else:
        if d == -10: return False  # even-z diagonal: no value-1 at all
        if d == -9: return _bk(off, 6) or R >= z + 12
        if d == -8: return _bk(off, 5)
        if d == -7: return _bk(off, 6) or R >= z + 12
        if d == -6: return _bk(off, 6)
        if d == -5: return _bk(off, 7) or R >= z + 14
        if d == -4: return _bk(off, 6)
        if d == -3: return _bk(off, 7) or R >= z + 14
        if d == -2: return _bk(off, 7)
        if d == -1: return _bk(off, 8) or R >= z + 16
        if d == 0: return _bk(off, 7)
        if d == 1: return _bk(off, 8) or R >= z + 16
        if d == 2: return _bk(off, 8)
        if d == 3: return _bk(off, 9) or R >= z + 18
        if d == 4: return _bk(off, 8)
        if d == 5: return _bk(off, 9) or R >= z + 18
        if d == 6: return _bk(off, 9)
        if d == 7: return _bk(off, 10) or R >= z + 20
        if d == 8: return _bk(off, 9)
        if d == 9: return _bk(off, 10) or R >= z + 20
        if d == 10: return _bk(off, 10)
        return base10 or band or tail  # d >= 11 (sweep included)

def cand10(z, x, R):
    if R <= 0:
        return 0
    if in_T10(z, x, R):
        return 2
    if in_P10(z, x, R):
        return 1
    return 0

def main():
    if len(sys.argv) == 1 or (len(sys.argv) > 1 and sys.argv[1] == 'selfcheck'):
        n = mm = ov = 0
        bad_ex = []
        for line in open('probe_rows.txt'):
            head, body = line.split('::')
            meta = dict(p.split('=') for p in head.split())
            z, x = int(meta['z']), int(meta['x'])
            vals = []
            for seg in body.split():
                v, c = seg.split('x')
                vals.extend([int(v)] * int(c))
            for i, v in enumerate(vals):
                R = i + 1
                n += 1
                c = cand10(z, x, R)
                if c != v:
                    mm += 1
                    if len(bad_ex) < 20:
                        bad_ex.append((z, x, R, v, c))
                if in_T10(z, x, R) and in_P10(z, x, R):
                    ov += 1
        print("probe points:", n, "mismatch:", mm, "overlap:", ov)
        for t in bad_ex:
            print("BAD", t)
        return
    print(__doc__)

if __name__ == '__main__':
    main()
