    # independent recomputation of the declared probe box (z=0..30, x=19..z+37,
    # R<=x+z+40); no input from probe_rows.txt
    rows = pts = 0
    for z in range(0, 31):
        for x in range(19, z + 38):
            rows += 1
            pts += x + z + 40
    return rows, pts

