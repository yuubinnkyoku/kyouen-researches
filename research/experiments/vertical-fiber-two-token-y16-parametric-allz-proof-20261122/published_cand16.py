import sys

Y = 16

def q_odd(k):
    return k if k % 2 == 1 else k - 1

def single_token_val(S, R):
    # K0832 published single-token closed form, z-independent rows (merge region)
    if R == 0:
        return 0
    if R % 2 == 1 and R <= q_odd(S):
        return 2
    if S % 2 == 1 and R >= q_odd(S) + 1:
        return 1
    return 0

def in_T16(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        S = x + Y
        return R % 2 == 1 and R <= q_odd(S)
    d = x - z
    o = R - z
    if d == -Y:
        if R % 2 == 1 and R <= (z if z % 2 == 1 else z - 1):
            return True
        if z % 2 == 1:
            return o % 2 == 0 and 2 <= o <= Y
        return o % 2 == 1 and 1 <= o <= Y - 1
    if z % 2 == 1:
        ladder = R % 2 == 1 and R <= z
        if (d + 3 * Y) % 4 == 0 and -Y + 4 <= d <= Y:
            if R == z + (d + 3 * Y) // 2:
                return True
        if d == Y + 1:
            return ladder or (o % 2 == 0 and 2 * Y <= o <= x + Y)
        if d >= Y + 2:
            return ladder or R == z + 2 * Y
        return ladder
    else:
        ladder = R % 2 == 1 and R <= z - 1
        if (d + 3 * Y) % 4 == 2 and -Y + 2 <= d <= Y - 2:
            if R == z + (d + 3 * Y) // 2:
                return True
        if d == Y + 1:
            return ladder or (o % 2 == 1 and 2 * Y + 1 <= o <= x + Y)
        if d >= Y + 2:
            return ladder or R == z + 2 * Y + 1
        return ladder

def _bk(off, k):
    return 1 <= off <= 2 * k - 1 and off % 2 == 1

def in_P16(z, x, R):
    if R <= 0:
        return False
    if x <= z - Y - 1:
        S = x + Y
        return S % 2 == 1 and R >= q_odd(S) + 1
    d = x - z
    off = R - z
    b16 = _bk(off, Y)
    band = off % 2 == 0 and 2 * Y + 2 <= off <= x + Y          # steady/sweep even band
    tail = x % 2 == 1 and R >= x + z + Y + 1                    # S odd rows (y=16: x odd)
    if z % 2 == 1:
        if -Y <= d <= Y and d % 2 == 0:
            k = (d + 3 * Y + 2) // 4          # I rows: b_k U I[th) (diag d=-16 incl., k=8)
            th = 2 * k + (1 if (d + 3 * Y) % 4 == 0 else 0)   # pin rows (d==y mod4): 2k+1; skew: 2k
            return _bk(off, k) or off >= th
        if -Y + 1 <= d <= Y - 1 and d % 2 == 1:
            return _bk(off, (d + 3 * Y + 1) // 4)  # base rows d odd in [-15,15]
        if d == Y + 1:
            return b16                          # sweep row, base type: z odd x even
        return b16 or band or tail              # d >= Y+2 steady rows
    else:
        if d == -Y:
            return False                        # even-z diagonal: no value-1 (9th consecutive candidate family)
        if -Y + 1 <= d <= Y - 1 and d % 2 == 1:
            k = (d + 3 * Y - 1) // 4           # I rows: b_k U I[2k+1)
            return _bk(off, k) or off >= 2 * k + 1
        if -Y + 2 <= d <= Y and d % 2 == 0:
            return _bk(off, (d + 3 * Y + 1) // 4)  # base rows d even in [-14,16] (d=16 saturates k=Y=16)
        return b16 or band or tail              # d >= Y+1 (sweep 17 incl.: x odd -> tail active)

def cand16(z, x, R):
    if R <= 0:
        return 0
    if in_T16(z, x, R):
        return 2
    if in_P16(z, x, R):
        return 1
    return 0

