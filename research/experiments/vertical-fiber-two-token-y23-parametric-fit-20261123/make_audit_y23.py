    if x == 25:
        return R % 2 == 1 and 7 <= R <= 49
    if x == 26:
        # O[7,55] U E[52,54] U I[56,inf)
        return (R % 2 == 1 and R <= 55) or (R % 2 == 0 and 52 <= R <= 54) or R >= 56
    if x == 27:
        return R % 2 == 1 and 7 <= R <= 49
    if x == 28:
        # O[7,57] U E[52,56] U I[58,inf)
        return (R % 2 == 1 and R <= 57) or (R % 2 == 0 and 52 <= R <= 56) or R >= 58
    if x == 29:
        return R % 2 == 1 and 7 <= R <= 51
    if x == 30:
        # O[7,51] U E[54,58] U I[60,inf)
        return (R % 2 == 1 and R <= 51) or (R % 2 == 0 and 54 <= R <= 58) or R >= 60
    if x >= 31 and x % 2 == 1:
        # O[7,51] U E[54, x+29]
        return (R % 2 == 1 and R <= 51) or (R % 2 == 0 and 54 <= R <= x + 29)
    if x >= 32 and x % 2 == 0:
        # O[7,51] U E[54,inf) U O[x+31,inf)
        return (R % 2 == 1 and (R <= 51 or R >= x + 31)) or (R % 2 == 0 and R >= 54)
    raise AssertionError("unreachable x=%d" % x)


