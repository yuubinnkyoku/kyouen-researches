    # independent recomputation of the declared probe box (z=0..30, x=18..z+35,
    # R<=x+z+38); no input from probe_rows.txt
    rows = pts = 0
    for z in range(0, 31):
        for x in range(18, z + 36):
            rows += 1
            pts += x + z + 38
    return rows, pts

