#!/usr/bin/env python3
"""Verify the Möbius symmetry used to fix three points for the q=7 search.

Facts checked computationally:
1. Each of the three generators g1: x->x+1, g2: x->lambda*x, g3: x->1/x
   (lambda primitive in GF(49), alpha^2=6, label=b+7a) maps the board's
   block set onto itself.
2. The group generated by g1,g2,g3 is 3-transitive on the 50 points:
   BFS on ordered triples from (0,7,49) reaches all 50*49*48 ordered triples.
"""
import json
import sys
from collections import deque
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "output"
Q = 7
C = 6
INF = 49


def load_blocks():
    with open(OUT / f"board_q{Q}.json", "r", encoding="utf-8") as f:
        data = json.load(f)
    return frozenset(frozenset(bl) for bl in data["blocks"])


def fadd(x, y):
    return ((x[0] + y[0]) % Q, (x[1] + y[1]) % Q)


def fmul(x, y):
    a, b = x
    d, e = y
    return ((a * d + b * e * C) % Q, (a * e + b * d) % Q)


def finv(x):
    a, b = x
    norm = (a * a - C * b * b) % Q
    assert norm != 0
    inv = pow(norm, Q - 2, Q)
    return ((a * inv) % Q, ((-b) * inv) % Q)


def fdiv(x, y):
    return fmul(x, finv(y))


def label_to_field(L):
    return (L // Q, L % Q)


def field_to_label(x):
    return (x[1] + Q * x[0]) % (Q * Q)


def apply(M, L):
    a, b, c, d = M
    if L == INF:
        return INF if c == (0, 0) else field_to_label(fdiv(a, c))
    x = label_to_field(L)
    num = fadd(fmul(a, x), b)
    den = fadd(fmul(c, x), d)
    if den == (0, 0):
        return INF
    return field_to_label(fdiv(num, den))


def perm_of(M):
    return tuple(apply(M, L) for L in range(INF + 1))


def main():
    board = load_blocks()
    lam = (1, 2)
    gens = [
        ((1, 0), (1, 0), (0, 0), (1, 0)),   # x+1
        (lam, (0, 0), (0, 0), (1, 0)),      # lambda*x
        ((0, 0), (1, 0), (1, 0), (0, 0)),   # 1/x
    ]
    for i, M in enumerate(gens):
        p = perm_of(M)
        assert sorted(p) == list(range(INF + 1)), "not a permutation"
        img = frozenset(frozenset(p[x] for x in bl) for bl in board)
        print(f"generator {i}: automorphism = {img == board}")
        assert img == board
    # BFS on ordered triples
    start = (0, 7, 49)
    seen = {start}
    dq = deque([start])
    perms = [perm_of(M) for M in gens]
    target = 50 * 49 * 48
    while dq and len(seen) < target:
        t = dq.popleft()
        for p in perms:
            u = (p[t[0]], p[t[1]], p[t[2]])
            if u not in seen:
                seen.add(u)
                dq.append(u)
    print("ordered triples reached:", len(seen), "of", target)
    assert len(seen) == target
    # Also confirm PGL sharp 3-transitivity group order not needed; BFS suffices.
    print("3-transitivity verified; the fixed triple (0,7,49) is WLOG.")


if __name__ == "__main__":
    main()
