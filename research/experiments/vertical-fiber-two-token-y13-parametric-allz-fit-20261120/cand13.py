import sys

Y = 13

def q_odd(k):
    return k if k % 2 == 1 else k - 1

def single_token_val(S, R):
    # K0832 published single-token closed form
    if R <= 0:
        return 0
    if R % 2 == 1 and R <= q_odd(S):
        return 2
    if S % 2 == 1 and R >= q_odd(S) + 1:
        return 1
    return 0

def cand13(z, x, R):
    if R <= 0:
        return 0
    d = x - z
    off = R - z
    pbase = off >= 1 and off % 2 == 1   # odd positive offset
    if d <= -Y + 1:                       # deep zone: x <= z-12
        return single_token_val(x + 11, R)
    if z % 2 == 1:
        ladder = R % 2 == 1 and R <= z
    else:
        ladder = R % 2 == 1 and R <= z - 1
    T = ladder
    P = False
    if z % 2 == 1:
        if d == -11:
            T = T or (off % 2 == 0 and 2 <= off <= 10)
            P = (pbase and off <= 11) or off >= 12
        elif x % 2 == 0:                  # class A
            if z >= 15:
                k = (d + 23) // 2
                T = T or R == z + d + 21
                P = (pbase and off <= 2 * k - 1) or off >= 2 * k
            else:                          # z <= 13
                if z == 13:
                    T = T or R == z + d + 21 or R == z + d + 23
                P = pbase or off >= x + 11
        else:                             # class B (x odd)
            capc = d + 21 if z >= 15 else x + 10
            P = pbase and off <= capc
    else:
        if d == -11:
            T = T or (pbase and off <= 11)
        elif x % 2 == 0:                  # class D
            if z >= 14:
                k = (d + 22) // 2
                P = (pbase and off <= 2 * k - 1) or off >= 2 * k
            else:                          # z <= 12
                P = pbase or off >= x + 11
        else:                             # class C (x odd)
            if z >= 16:
                T = T or R == z + d + 22
                P = pbase and off <= d + 20
            elif z == 14:
                T = T or R == z + d + 22 or R == z + d + 24
                P = pbase and off <= d + 20
            else:                          # z <= 12
                P = pbase and off <= x + 10
    if T:
        return 2
    if P:
        return 1
    return 0

def main():
    if len(sys.argv) == 1 or (len(sys.argv) > 1 and sys.argv[1] == 'selfcheck'):
        n = mm = ov = 0
        bad_ex = []
        for line in open('probe_rows.txt'):
            head, body = line.split('::')
            meta = dict(p.split('=') for p in head.split())
            z, x = int(meta['z']), int(meta['x'])
            vals = []
            for seg in body.split():
                v, c = seg.split('x')
                vals.extend([int(v)] * int(c))
            for R in range(1, len(vals) + 1):
                got = cand13(z, x, R)
                exp = vals[R - 1]
                n += 1
                if got != exp:
                    mm += 1
                    if len(bad_ex) < 25:
                        bad_ex.append((z, x, R, exp, got))
                if got == 2 and exp == 1 or got == 1 and exp == 2:
                    ov += 1
        print(f"probe points: {n} mismatch: {mm} overlap: {ov}")
        for b in bad_ex:
            print("BAD", b)

if __name__ == '__main__':
    main()
